import { describe, expect, it } from 'vitest'
import { generate } from '../../src/generate/index'
import { loadModel } from '../../src/model/load'
import { fixtureModelFiles } from '../model/fixture'

// codegen-architecture R2: a route of an API data source and its composable read one HTTP contract, as a module's do (T4b): its method,
// its path, the schemas of what it reads and the type of what it answers. Neither spells the route on its own, so they can't drift.

const loaded = loadModel(fixtureModelFiles())
if (!loaded.ok) throw new Error(JSON.stringify(loaded.problems))
const generated = generate(loaded.model)
const read = (path: string) => generated.find(file => file.path === path)?.content
const HEADER = '// Generated by bildr from .bildr/datasources/catalog.json. Editing this file detaches it from the editor.'
const CONTRACTS = 'layers/apis/shared/contracts/catalog'

describe('the HTTP contract of an API data source\'s route', () => {
  it('a query: its query string (as text, coerced) and its answer', () => {
    expect(read(`${CONTRACTS}/products.ts`)).toBe([
      HEADER,
      'import { z } from \'zod\'',
      'import type { Product } from \'../../domain/catalog/entities/product\'',
      '',
      '/** The HTTP contract of the query "products" of the "catalog" API: its route and its composable both read it. */',
      'export const productsContract = {',
      '  method: \'GET\',',
      '  path: \'/api/apis/catalog/products\',',
      '  /** Its parameters, read from the query string (everything arrives as text). */',
      '  query: z.object({',
      '    category: z.string().optional(),',
      '    locale: z.string().optional()',
      '  })',
      '} as const',
      '',
      '/** What the route answers. */',
      'export type ProductsResponse = Product[]',
      ''
    ].join('\n'))
  })

  it('an action with a body: the model\'s schema, and its answer', () => {
    expect(read(`${CONTRACTS}/create-product.ts`)).toBe([
      HEADER,
      'import { type Product, ProductSchema } from \'../../domain/catalog/entities/product\'',
      '',
      '/** The HTTP contract of the action "createProduct" of the "catalog" API: its route and its composable both read it. */',
      'export const createProductContract = {',
      '  method: \'POST\',',
      '  path: \'/api/apis/catalog/create-product\',',
      '  body: ProductSchema',
      '} as const',
      '',
      '/** What the route answers. */',
      'export type CreateProductResponse = Product',
      ''
    ].join('\n'))
  })

  it('an action that answers nothing answers undefined (the route\'s 204)', () => {
    expect(read(`${CONTRACTS}/delete-product.ts`)).toContain([
      '  method: \'DELETE\',',
      '  path: \'/api/apis/catalog/delete-product\',',
      '  /** Its parameters, read from the query string (everything arrives as text). */',
      '  query: z.object({',
      '    id: z.coerce.number().int()',
      '  })',
      '} as const',
      '',
      '/** What the route answers. */',
      'export type DeleteProductResponse = undefined'
    ].join('\n'))
  })

  it('the route validates with the contract and declares its answer as it', () => {
    expect(read('layers/apis/server/api/apis/catalog/products.get.ts')).toBe([
      HEADER,
      'import { defineEventHandler, getValidatedQuery } from \'nuxt/server\'',
      'import { type ProductsResponse, productsContract } from \'../../../../shared/contracts/catalog/products\'',
      'import { catalogErrorStatus, useCatalogApi } from \'../../../utils/catalog\'',
      '',
      'export default defineEventHandler(async (event): Promise<ProductsResponse> => {',
      '  const input = await getValidatedQuery(event, productsContract.query)',
      '  return unwrapOrThrow(await useCatalogApi().products(input), catalogErrorStatus)',
      '})',
      ''
    ].join('\n'))
    expect(read('layers/apis/server/api/apis/catalog/create-product.post.ts')).toContain('  const body = await readValidatedBody(event, createProductContract.body)\n')
    expect(read('layers/apis/server/api/apis/catalog/delete-product.delete.ts')).toContain('  const input = await getValidatedQuery(event, deleteProductContract.query)\n')
  })

  it('the composable calls the contract\'s path with its method, and reads the answer as it', () => {
    expect(read('layers/apis/app/composables/apis/useCatalogProducts.ts')).toContain([
      'import { type ProductsResponse, productsContract } from \'../../../shared/contracts/catalog/products\'',
      'import type { CatalogError } from \'../../../shared/domain/catalog/errors\''
    ].join('\n'))
    expect(read('layers/apis/app/composables/apis/useCatalogProducts.ts')).toContain('  useApiQuery<ProductsInput, ProductsResponse, CatalogError>({\n')
    expect(read('layers/apis/app/composables/apis/useCatalogProducts.ts')).toContain(
      '    fetch: (query, signal) => fromRoute($fetch<ProductsResponse>(productsContract.path, { method: productsContract.method, query, signal }))\n')
    expect(read('layers/apis/app/composables/apis/useCatalogCreateProduct.ts')).toContain(
      '    ({ body }) => fromRoute($fetch<CreateProductResponse>(createProductContract.path, { method: createProductContract.method, body })),\n')
    expect(read('layers/apis/app/composables/apis/useCatalogDeleteProduct.ts')).toContain(
      '    query => fromRoute($fetch<DeleteProductResponse>(deleteProductContract.path, { method: deleteProductContract.method, query })),\n')
  })

  it('a source that runs in the browser has no route, so no contract', () => {
    expect(generated.filter(file => file.path.startsWith('layers/apis/shared/contracts/weather'))).toEqual([])
  })
})

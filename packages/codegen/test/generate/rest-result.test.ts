import { describe, expect, it } from 'vitest'
import { generate } from '../../src/generate'
import { loadModel } from '../../src/model/load'
import type { Model } from '../../src/model/load'
import { fixtureModelFiles } from '../model/fixture'

// codegen-architecture R1': a module entity on a REST data source is read the way the apis layer reads an API. Its port answers a
// Result, its adapter validates the answer and maps it to the domain, and a failure is the source's typed error, never a throw.
// A list-only REST repository goes first (the golden's quotes).

const fixtureModel = (): Model => {
  const result = loadModel(fixtureModelFiles())
  if (!result.ok) throw new Error(JSON.stringify(result.problems))
  return result.model
}

const files = generate(fixtureModel())
const content = (path: string) => files.find(file => file.path === path)?.content
const BLOG = 'layers/blog'

describe('a list-only REST repository answers a Result', () => {
  it('the source has its errors in the module\'s domain', () => {
    expect(content(`${BLOG}/shared/domain/sources/quotes.ts`)).toBe([
      '// Generated by bildr from .bildr/datasources/quotes.json. Editing this file detaches it from the editor.',
      '',
      '/** Every expected failure of a call to the "quotes" REST data source: it answered with an error, or it answered something unexpected. */',
      'export type QuotesSourceError =',
      '  | { type: \'remote_failed\', message: string, status: number }',
      '  | { type: \'invalid_answer\', message: string }',
      '',
      '/** `status` is what the source answered, or 0 when it didn\'t answer; `detail` finishes "The "quotes" data source …". */',
      'export const quotesFailed = (status: number, detail: string): QuotesSourceError => ({ type: \'remote_failed\', message: `The "quotes" data source ${detail}.`, status })',
      '',
      '/** The answer is not what the model says. The error has no detail: it reaches the browser, and the detail (field paths, what was expected) is for the server log. */',
      'export const quotesInvalidAnswer = (): QuotesSourceError => ({ type: \'invalid_answer\', message: \'The "quotes" data source answered something unexpected\' })',
      ''
    ].join('\n'))
  })

  it('the module\'s error union has the source\'s errors, and its status map their statuses', () => {
    const errors = content(`${BLOG}/shared/domain/errors.ts`)!
    expect(errors).toContain('import type { QuotesSourceError } from \'./sources/quotes\'\n')
    expect(errors).toContain('  | { type: \'post_not_found\', message: string, id: string }\n  | QuotesSourceError\n')
    expect(content(`${BLOG}/server/utils/blog.ts`)).toContain('  post_not_found: 404,\n  remote_failed: 502,\n  invalid_answer: 502\n} satisfies Record<BlogError[\'type\'], number>')
  })

  it('the port and the list use-case answer the page or the source\'s error', () => {
    expect(content(`${BLOG}/server/application/ports/quote-repository.ts`)).toContain('  list(page: PageRequest): Promise<Result<Page<Quote>, QuotesSourceError>>\n')
    expect(content(`${BLOG}/server/application/queries/list-quotes.ts`)).toContain('  (page: PageRequest): Promise<Result<Page<Quote>, QuotesSourceError>> => quotes.list(page)')
  })

  it('the adapter validates the answer with the entity\'s field rules under their remote names, and maps it', () => {
    const adapter = content(`${BLOG}/server/infrastructure/repositories/quote.rest.ts`)!
    expect(adapter).toContain([
      'const QuotesAnswerSchema = z.object({',
      '  quotes: z.array(z.object({ id: QuoteSchema.shape.id, quote: QuoteSchema.shape.text, author: QuoteSchema.shape.author })),',
      '  total: z.number()',
      '})'
    ].join('\n'))
    expect(adapter).toContain([
      'export const restQuoteRepository = (http: ApiClient<QuotesSourceError>, onInvalidAnswer?: (detail: string) => void): QuoteRepository => ({',
      '  async list({ limit, offset }) {',
      '    const answer = await http(\'/quotes\', { method: \'GET\', query: { limit, skip: offset } })',
      '    if (!answer.ok) return answer',
      '    const page = QuotesAnswerSchema.safeParse(answer.value)',
      '    if (!page.success) {',
      '      onInvalidAnswer?.(page.error.message)',
      '      return err(quotesInvalidAnswer())',
      '    }',
      '    return ok({',
      '      items: page.data.quotes.map(row => ({ id: row.id, text: row.quote, author: row.author })),',
      '      total: page.data.total',
      '    })',
      '  }',
      '})'
    ].join('\n'))
    expect(adapter).not.toContain('useRemote')
  })

  it('the composition root builds the source\'s client from runtimeConfig, and logs an invalid answer\'s detail on the server', () => {
    const root = content(`${BLOG}/server/utils/blog.ts`)!
    expect(root).toContain([
      'const quotesClient = (): ApiClient<QuotesSourceError> => {',
      '  const { baseUrl, apiKey } = useRuntimeConfig().datasources.quotes',
      '  const headers: Record<string, string> = { accept: \'application/json\' }',
      '  if (apiKey) headers.authorization = `Bearer ${apiKey}`',
      '  return resultClient(createHttpClient({ baseUrl, headers }), failure => quotesFailed(failure.status, failure.message))',
      '}'
    ].join('\n'))
    expect(root).toContain('  const quotes = restQuoteRepository(quotesClient(), detail => console.error(\'The "quotes" data source answered something unexpected: \' + detail))\n')
    expect(root).not.toContain('useRemote')
  })

  it('the list route answers the page, or throws the source\'s error with its status', () => {
    expect(content(`${BLOG}/server/api/blog/quotes/index.get.ts`)).toContain('  return unwrapOrThrow(await useBlog().listQuotes(page), blogErrorStatus)\n')
  })

  it('refuses an action error typed like one of the source\'s (one type, two shapes)', () => {
    const model = structuredClone(fixtureModel())
    model.modules.blog!.actions[0]!.errors.push({ type: 'remote_failed', status: 500, message: 'Nope.' })
    expect(() => generate(model)).toThrow('the error type "remote_failed" is the "quotes" data source\'s: name it another way')
  })
})

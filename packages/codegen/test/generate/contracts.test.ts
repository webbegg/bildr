import { describe, expect, it } from 'vitest'
import { generate } from '../../src/generate'
import { loadModel } from '../../src/model/load'
import type { Model } from '../../src/model/load'
import { fixtureModelFiles } from '../model/fixture'

// codegen-architecture T4b: each route of a module has one HTTP contract in `shared/contracts/` (method, path, what it reads, what it
// answers). The route and its client (an action's composable, an entity's collection) both read it, so the two can't drift.

const fixtureModel = (): Model => {
  const result = loadModel(fixtureModelFiles())
  if (!result.ok) throw new Error(JSON.stringify(result.problems))
  return result.model
}

const files = generate(fixtureModel())
const content = (path: string) => files.find(file => file.path === path)?.content
const BLOG = 'layers/blog'

describe('the HTTP contract of a route', () => {
  it('an action with a body: its method, path and body schema, and what it answers', () => {
    expect(content(`${BLOG}/shared/contracts/create-post.ts`)).toBe([
      '// Generated by bildr from .bildr/modules/blog/actions/create-post.json. Editing this file detaches it from the editor.',
      'import { type Post, NewPostSchema } from \'#blog/domain/post\'',
      '',
      '/** The HTTP contract of the action "Create post": its route and its client both read it. */',
      'export const createPostContract = {',
      '  method: \'POST\',',
      '  path: \'/api/blog/posts\',',
      '  body: NewPostSchema',
      '} as const',
      '',
      '/** What the route answers. */',
      'export type CreatePostResponse = Post',
      ''
    ].join('\n'))
  })

  it('an action with a route parameter: its path is a function of it, and the parameter has its schema', () => {
    expect(content(`${BLOG}/shared/contracts/publish-post.ts`)).toBe([
      '// Generated by bildr from .bildr/modules/blog/actions/publish-post.json. Editing this file detaches it from the editor.',
      'import { IdSchema } from \'#core/kernel/ids\'',
      'import type { Post } from \'#blog/domain/post\'',
      '',
      '/** The HTTP contract of the action "Publish post": its route and its client both read it. */',
      'export const publishPostContract = {',
      '  method: \'POST\',',
      '  path: (id: string) => `/api/blog/posts/${id}/publish`,',
      '  params: { id: IdSchema }',
      '} as const',
      '',
      '/** What the route answers. */',
      'export type PublishPostResponse = Post',
      ''
    ].join('\n'))
  })

  it('an entity\'s list: its query schema and the page it answers', () => {
    expect(content(`${BLOG}/shared/contracts/list-posts.ts`)).toBe([
      '// Generated by bildr from .bildr/modules/blog/repositories/post.json. Editing this file detaches it from the editor.',
      'import { type Page, PageRequestSchema } from \'#core/kernel/page\'',
      'import type { Post } from \'#blog/domain/post\'',
      '',
      '/** The HTTP contract of the Post list: its route and the posts collection both read it. */',
      'export const listPostsContract = {',
      '  method: \'GET\',',
      '  path: \'/api/blog/posts\',',
      '  query: PageRequestSchema',
      '} as const',
      '',
      '/** What the route answers. */',
      'export type ListPostsResponse = Page<Post>',
      ''
    ].join('\n'))
  })

  it('refuses a response type named like the entity it answers (two declarations of one name)', () => {
    const clashing = structuredClone(fixtureModel())
    clashing.modules.blog!.entities.find(entry => entry.name === 'Post')!.name = 'PublishPostResponse'
    expect(() => generate(clashing)).toThrow('the contract\'s response type PublishPostResponse would take the name of the PublishPostResponse it answers')
  })

  it('refuses a route path with a segment that is not one of its parameters (its template would read an undeclared name)', () => {
    const model = structuredClone(fixtureModel())
    model.modules.blog!.actions.find(entry => entry.name === 'publishPost')!.http.path = '/posts/:postId/publish/:id'
    expect(() => generate(model)).toThrow('/posts/:postId/publish/:id has :postId, which is not one of its route parameters (id)')
  })

  it('the module\'s layer has an alias for its contracts, and so do the project\'s tests', () => {
    expect(content(`${BLOG}/nuxt.config.ts`)).toContain('    \'#blog/contracts\': here(\'./shared/contracts\'),\n    \'#blog/domain\': here(\'./shared/domain\')\n')
    expect(content('vitest.config.ts')).toContain('      \'#blog/contracts\': here(\'./layers/blog/shared/contracts\'),\n')
  })
})

describe('the route reads its contract and answers its response type', () => {
  it('a body', () => {
    expect(content(`${BLOG}/server/api/blog/posts/index.post.ts`)).toBe([
      '// Generated by bildr from .bildr/modules/blog/actions/create-post.json. Editing this file detaches it from the editor.',
      'import { defineEventHandler, readValidatedBody } from \'nuxt/server\'',
      'import { type CreatePostResponse, createPostContract } from \'#blog/contracts/create-post\'',
      '',
      'export default defineEventHandler(async (event): Promise<CreatePostResponse> => {',
      '  const input = await readValidatedBody(event, createPostContract.body)',
      '  return unwrapOrThrow(await useBlog().createPost(input), blogErrorStatus, event)',
      '})',
      ''
    ].join('\n'))
  })

  it('a route parameter', () => {
    expect(content(`${BLOG}/server/api/blog/posts/[id]/publish.post.ts`)).toContain([
      'import { type PublishPostResponse, publishPostContract } from \'#blog/contracts/publish-post\'',
      '',
      'export default defineEventHandler(async (event): Promise<PublishPostResponse> => {',
      '  const id = publishPostContract.params.id.parse(getRouterParam(event, \'id\'))'
    ].join('\n'))
  })

  it('a list', () => {
    expect(content(`${BLOG}/server/api/blog/posts/index.get.ts`)).toContain([
      'import { type ListPostsResponse, listPostsContract } from \'#blog/contracts/list-posts\'',
      '',
      'export default defineEventHandler(async (event): Promise<ListPostsResponse> => {',
      '  const page = await getValidatedQuery(event, listPostsContract.query)'
    ].join('\n'))
  })
})

describe('the client reads the same contract', () => {
  it('an action\'s composable calls the contract\'s path with its method, typed by its response', () => {
    const create = content(`${BLOG}/app/composables/blog/useCreatePost.ts`)!
    expect(create).toContain('import { type CreatePostResponse, createPostContract } from \'#blog/contracts/create-post\'')
    expect(create).toContain('fromRoute<CreatePostResponse, BlogError>($fetch<CreatePostResponse>(createPostContract.path, { method: createPostContract.method, body: input }))')
    const publish = content(`${BLOG}/app/composables/blog/usePublishPost.ts`)!
    expect(publish).toContain('fromRoute<PublishPostResponse, BlogError>($fetch<PublishPostResponse>(publishPostContract.path(id), { method: publishPostContract.method }))')
    expect(publish).not.toContain('/api/blog')
  })

  it('an entity\'s collection syncs from its list contract', () => {
    const collection = content(`${BLOG}/app/data/posts.collection.ts`)!
    expect(collection).toContain('import { type ListPostsResponse, listPostsContract } from \'#blog/contracts/list-posts\'')
    expect(collection).toContain('queryFn: ({ signal }) => $fetch<ListPostsResponse>(listPostsContract.path, { method: listPostsContract.method, query: { limit: 500 }, signal }),')
    expect(collection).toContain('select: (page: ListPostsResponse) => page.items,')
    expect(collection).not.toContain('/api/blog')
  })
})

import { describe, expect, it } from 'vitest'
import { generateActions } from '../../src/generate/actions'
import { loadModel } from '../../src/model/load'
import type { Model } from '../../src/model/load'
import { fixtureModelFiles } from '../model/fixture'

// codegen-architecture T4a: what an action changes is one pure function of the domain (`<entity>.rules.ts`), derived from the
// action's steps. The use-case calls it, and so does the optimistic update when it says the same as the steps (or nothing).

const fixtureModel = (): Model => {
  const result = loadModel(fixtureModelFiles())
  if (!result.ok) throw new Error(JSON.stringify(result.problems))
  return result.model
}

/** The blog fixture with the "Publish post" action's optimistic update changed by `edit`. */
const withPublishOptimistic = (edit: (optimistic: Record<string, unknown>) => void) => {
  const model = structuredClone(fixtureModel())
  const action = model.modules.blog!.actions.find(entry => entry.name === 'publishPost')!
  edit(action.client.optimistic as Record<string, unknown>)
  return generateActions(model)
}

const content = (files: ReturnType<typeof generateActions>, path: string) => files.find(file => file.path === path)?.content
const RULES = 'layers/blog/shared/domain/post.rules.ts'
const PUBLISH = 'layers/blog/app/composables/blog/usePublishPost.ts'

describe('the domain rules of an action', () => {
  const files = generateActions(fixtureModel())

  it('are one pure function per action that sets something, next to the entity it changes', () => {
    expect(content(files, RULES)).toBe([
      '// Generated by bildr from the blog module\'s actions. Editing this file detaches it from the editor.',
      'import type { NewPost, Post } from \'./post\'',
      '',
      '/** What "Create post" sets on a new Post. The use-case and its optimistic update both apply it. */',
      'export const createPostChange = (input: NewPost, at: string): Pick<Post, \'publishedAt\'> => ({ publishedAt: input.published ? at : null })',
      '',
      '/** What "Publish post" changes on a Post, or undefined when it changes nothing. The use-case and its optimistic update both apply it. */',
      // It takes only the fields it reads: the optimistic update passes the collection's draft, whose defaulted fields are optional.
      'export const publishPostChange = (post: Partial<Pick<Post, \'published\'>>, at: string): Pick<Post, \'published\' | \'publishedAt\'> | undefined => {',
      '  if (post.published) return undefined',
      '  return { published: true, publishedAt: at }',
      '}',
      ''
    ].join('\n'))
  })

  it('the use-cases apply them, stamping the timestamps themselves', () => {
    const create = content(files, 'layers/blog/server/application/actions/create-post.ts')!
    expect(create).toContain('import { createPostChange } from \'#blog/domain/post.rules\'')
    expect(create).toContain('return ok(await posts.create({ ...data, ...createPostChange(data, at), createdAt: at, updatedAt: at }))')
    const publish = content(files, 'layers/blog/server/application/actions/publish-post.ts')!
    expect(publish).toContain('import { publishPostChange } from \'#blog/domain/post.rules\'')
    expect(publish).toContain([
      '    if (!post) return err(postNotFound(id))',
      '    const at = now()',
      '    const postChange = publishPostChange(post, at)',
      '    if (!postChange) return ok(post)',
      '    return ok(await posts.update(id, { ...post, ...postChange, updatedAt: at }))'
    ].join('\n'))
    // The guard moved into the rule: the use-case no longer reads the field itself.
    expect(publish).not.toContain('post.published')
  })

  it('the optimistic updates apply them too', () => {
    const create = content(files, 'layers/blog/app/composables/blog/useCreatePost.ts')!
    expect(create).toContain('import { createPostChange } from \'#blog/domain/post.rules\'')
    expect(create).toContain('        ...createPostChange(input, at), createdAt: at, updatedAt: at')
    const publish = content(files, PUBLISH)!
    expect(publish).toContain('import { publishPostChange } from \'#blog/domain/post.rules\'')
    expect(publish).toContain([
      '      postsCollection.update(id, (draft) => {',
      '        const change = publishPostChange(draft, now())',
      '        if (change) Object.assign(draft, change)',
      '      })'
    ].join('\n'))
  })

  it('an optimistic update that says nothing applies the rule', () => {
    const files = withPublishOptimistic((optimistic) => {
      delete optimistic.set
      delete optimistic.unless
    })
    expect(content(files, PUBLISH)).toContain('const change = publishPostChange(draft, now())')
  })

  it('an action that decides nothing (constants, the time) has no rule: its steps stay inline', () => {
    const model = structuredClone(fixtureModel())
    const actions = model.modules.blog!.actions
    const publish = actions.find(entry => entry.name === 'publishPost')!
    publish.steps = publish.steps.filter(step => step.kind !== 'return')
    delete (publish.client.optimistic as Record<string, unknown>).unless
    const create = actions.find(entry => entry.name === 'createPost')!
    const last = create.steps.at(-1) as Record<string, unknown>
    last.set = { publishedAt: { $now: true } }
    const files = generateActions(model)
    expect(content(files, RULES)).toBeUndefined()
    expect(content(files, PUBLISH)).toContain('        draft.published = true\n')
    expect(content(files, 'layers/blog/server/application/actions/publish-post.ts')).toContain('posts.update(id, { ...post, published: true, publishedAt: at, updatedAt: at })')
    expect(content(files, 'layers/blog/server/application/actions/create-post.ts')).toContain('posts.create({ ...data, publishedAt: at, createdAt: at, updatedAt: at })')
  })

  it('an optimistic update that says something else keeps its own code', () => {
    const otherSet = withPublishOptimistic((optimistic) => {
      optimistic.set = { published: true }
    })
    expect(content(otherSet, PUBLISH)).not.toContain('publishPostChange')
    expect(content(otherSet, PUBLISH)).toContain('        if (draft.published) return\n        draft.published = true\n')
    const noGuard = withPublishOptimistic((optimistic) => {
      delete optimistic.unless
    })
    expect(content(noGuard, PUBLISH)).not.toContain('publishPostChange')
  })
})

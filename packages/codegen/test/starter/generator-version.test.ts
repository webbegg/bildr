// codegen-architecture T6: a project made by an older generator is not regenerated until it is upgraded on purpose.
import { describe, expect, it } from 'vitest'
import { GENERATOR_VERSION, generatorHold } from '../../src/starter/starter'

describe('generatorHold', () => {
  it('lets a project of this generator through', () => {
    expect(GENERATOR_VERSION).toBe('0.2.0')
    expect(generatorHold(GENERATOR_VERSION)).toBeUndefined()
  })

  it('holds a project made before the last change that breaks generated code, saying how to upgrade', () => {
    const hold = generatorHold('0.1.0')!
    expect(hold).toContain('This project was generated by bildr\'s generator 0.1.0; this bildr generates 0.2.0, whose code differs')
    expect(hold).toContain('project_update { upgradeGenerator: true }')
    expect(hold).toContain('MIGRATING.md')
  })

  it('holds a project of a newer generator: this bildr would write older code over it', () => {
    expect(generatorHold('0.3.0')).toBe('This project was generated by bildr\'s generator 0.3.0, newer than this bildr\'s (0.2.0): update bildr to regenerate it')
    expect(generatorHold('1.0.0')).toContain('newer than this bildr\'s')
  })

  it('reads versions as numbers (0.10.0 is newer than 0.2.0), and holds one it can\'t read', () => {
    expect(generatorHold('0.10.0')).toContain('newer')
    expect(generatorHold('latest')).toBe('This project\'s generatorVersion "latest" is not a version (x.y.z): set it in .bildr/bildr.json')
  })
})

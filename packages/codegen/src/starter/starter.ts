import { loadModel } from '../model/load.ts'
import { ModuleNameSchema, RESERVED_MODULE_NAMES } from '../model/schemas.ts'
import { serializeModel, stringifyModelFile } from '../model/serialize.ts'
import type { GeneratedFile } from '../sync/plan.ts'
import { STARTER_CORE_FILES, STARTER_ROOT_FILES } from './core-files.ts'

/**
 * The starter kit (decision D9): everything a new bildr project needs, as an
 * initial `.bildr/` model plus the files of the first sync. The static core
 * layer comes from the golden fixture (`core-files.ts`); the files derived
 * from the model are rendered here until the generators (T5–T7) take over.
 */

export const STARTER_KIT_VERSION = '1'
export const GENERATOR_VERSION = '0.1.0'

export interface StarterKitOptions {
  /** Project name, shown in the app and the README. */
  name: string
  /** First feature module (kebab-case). Default `main`. */
  module?: string
}

export interface StarterKit {
  /** `.bildr/…` path → text, in canonical form. The manifest is not included: the first sync writes it. */
  model: Record<string, string>
  files: GeneratedFile[]
}

const MANAGED = 'Generated by bildr. Editing this file detaches it from the editor.'
const managedFrom = (source: string) => `Generated by bildr from ${source}. Editing this file detaches it from the editor.`
const vueHeader = (source: string) => `<!-- ${managedFrom(source)}; prefer overriding it from the root app/. -->`

const LINE_SEPARATOR = String.fromCharCode(0x2028)
const PARAGRAPH_SEPARATOR = String.fromCharCode(0x2029)

/**
 * A single-quoted TS string literal that is also safe inside an SFC `<script>`:
 * line terminators are escaped and `</` can't close the script block.
 */
const tsString = (value: string) => `'${value
  .replace(/\\/g, '\\\\')
  .replace(/'/g, '\\\'')
  .replace(/\n/g, '\\n')
  .replace(/\r/g, '\\r')
  .replaceAll(LINE_SEPARATOR, '\\u2028')
  .replaceAll(PARAGRAPH_SEPARATOR, '\\u2029')
  .replace(/<\//g, '<\\/')}'`
const packageName = (name: string) => name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '') || 'bildr-app'
const pascal = (name: string) => name.split('-').map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('')

const DEFAULT_THEME = {
  colors: {
    'primary': 'oklch(0.55 0.2 264)',
    'on-primary': 'oklch(0.99 0 0)',
    'surface': 'oklch(0.99 0 0)',
    'muted': 'oklch(0.5 0.02 264)',
    'border': 'oklch(0.9 0.01 264)'
  },
  fonts: { sans: '"Inter", ui-sans-serif, system-ui, sans-serif' }
}

export const starterKit = ({ name, module = 'main' }: StarterKitOptions): StarterKit => {
  const title = name.trim()
  if (!title) throw new Error('Give the project a name')
  if (!ModuleNameSchema.safeParse(module).success) throw new Error(`Module name "${module}": use lowercase letters, digits and dashes (kebab-case)`)
  if ((RESERVED_MODULE_NAMES as readonly string[]).includes(module)) throw new Error(`Module name "${module}" is reserved (Nuxt aliases and the core layer use it)`)

  const model = initialModel(title, module)
  const files: GeneratedFile[] = [
    ...Object.entries(STARTER_CORE_FILES).map(([path, content]) => ({ path, content, owner: 'managed' as const })),
    ...rootFiles(title, module),
    ...modelDerivedFiles(title, module)
  ]
  return { model, files: files.sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0) }
}

// ── The initial .bildr/ model ──────────────────────────────────────────

const initialModel = (title: string, module: string): Record<string, string> => {
  const raw: Record<string, unknown> = {
    '.bildr/bildr.json': { schemaVersion: 1, generatorVersion: GENERATOR_VERSION, starterKit: STARTER_KIT_VERSION, name: title, defaultModule: module, modules: [module] },
    '.bildr/theme.json': DEFAULT_THEME,
    '.bildr/datasources/main.json': { id: 'ds_main', name: 'main', kind: 'sqlite', env: { url: 'NUXT_DB_URL' }, defaults: { url: 'file:.data/app.db' } },
    '.bildr/layouts/main.json': {
      id: 'lay_main',
      name: 'main',
      slots: [{ id: 'children', name: 'children', nodeId: 'n_main' }, { id: 'footer', name: 'footer', nodeId: 'n_footer' }],
      root: {
        id: 'n_root', type: 'Container', style: { display: 'flex', direction: 'column', minHeight: 'screen' },
        children: [
          { id: 'n_header', type: 'Container', style: { borderBottom: 'border' }, children: [
            { id: 'n_nav', type: 'Row', style: { maxWidth: '4xl', mx: 'auto', align: 'center', p: '4' }, children: [
              { id: 'n_brand', type: 'Link', props: { to: { page: 'pg_index' }, text: { $bind: 'site.name' } }, style: { fontSize: 'lg', fontWeight: 'semibold' } }
            ] }
          ] },
          { id: 'n_main', type: 'Container', style: { maxWidth: '4xl', mx: 'auto', width: 'full', grow: '1', p: '4' }, children: [] },
          { id: 'n_footer', type: 'Container', style: { borderTop: 'border', p: '4', textAlign: 'center', fontSize: 'sm', color: 'muted' }, children: [
            { id: 'n_footer_text', type: 'Text', props: { text: { $bind: 'site.name' } } }
          ] }
        ]
      }
    },
    [`.bildr/modules/${module}/module.json`]: { id: `mod_${module.replaceAll('-', '_')}`, name: module, label: pascal(module), dependsOn: [] },
    [`.bildr/modules/${module}/pages/index.json`]: {
      id: 'pg_index', name: 'index', path: '/', layout: 'lay_main', seo: { title: title },
      root: { id: 'n_page', type: 'Page', style: { display: 'flex', direction: 'column', gap: '4' }, children: [
        { id: 'n_h1', type: 'Heading', props: { level: 1, text: `Welcome to ${title}` }, style: { fontSize: '3xl', fontWeight: 'semibold' } },
        { id: 'n_intro', type: 'Text', props: { text: 'Open the bildr editor to model your data and design your pages.' }, style: { color: 'muted' } }
      ] }
    }
  }
  const files = Object.fromEntries(Object.entries(raw).map(([path, value]) => [path, stringifyModelFile(value)]))
  const result = loadModel(files)
  if (!result.ok) throw new Error(`Starter model is invalid: ${result.problems.map(problem => `${problem.path}: ${problem.message}`).join('; ')}`)
  return serializeModel(result.model)
}


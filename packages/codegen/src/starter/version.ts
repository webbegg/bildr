/**
 * The generator's version (codegen-architecture T6): the shape of the code bildr writes, not the packages' version. A project keeps the
 * one it was made with (`.bildr/bildr.json` `generatorVersion`); bildr regenerates it only when its code is this generator's.
 */
export const GENERATOR_VERSION = '0.2.0'

/**
 * The versions whose generated code differs in ways the owner's own code (root `app/`, `server/`, a detached file) can feel: a
 * project made before one is held until its owner upgrades it, MIGRATING.md in hand. Newest last.
 */
const BREAKING_VERSIONS = ['0.2.0']

/** Where each upgrade is explained. */
const MIGRATING = 'https://github.com/webbegg/bildr/blob/main/MIGRATING.md'

const parts = (version: string): number[] | undefined => {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(version)
  return match ? match.slice(1).map(Number) : undefined
}

/** Negative, zero or positive as `a` is older than, the same as or newer than `b` (both x.y.z). */
const compare = (a: number[], b: number[]) => (a[0]! - b[0]!) || (a[1]! - b[1]!) || (a[2]! - b[2]!)

/** Whether `version` is a generator newer than this one: upgrading it would move its code back. */
export const isNewerGenerator = (version: string) => {
  const given = parts(version)
  return !!given && compare(given, parts(GENERATOR_VERSION)!) > 0
}

/**
 * Why bildr would not regenerate a project of generator `version`, or undefined when it does. A newer one would have its code
 * rewritten as an older bildr writes it; one made before a breaking version would break the owner's code that relies on the old.
 */
export const generatorHold = (version: string): string | undefined => {
  const given = parts(version)
  if (!given) return `This project's generatorVersion ${JSON.stringify(version)} is not a version (x.y.z): set it in .bildr/bildr.json`
  const current = parts(GENERATOR_VERSION)!
  if (isNewerGenerator(version)) return `This project was generated by bildr's generator ${version}, newer than this bildr's (${GENERATOR_VERSION}): update bildr to regenerate it`
  const crossed = BREAKING_VERSIONS.filter(breaking => compare(given, parts(breaking)!) < 0 && compare(parts(breaking)!, current) <= 0)
  if (!crossed.length) return undefined
  return [
    `This project was generated by bildr's generator ${version}; this bildr generates ${GENERATOR_VERSION}, whose code differs (${crossed.map(breaking => `${MIGRATING}#to-${breaking.replaceAll('.', '')}`).join(', ')}).`,
    'bildr keeps the app as it is until you upgrade: read MIGRATING.md, then run project_update { upgradeGenerator: true } (or set generatorVersion in .bildr/bildr.json).'
  ].join(' ')
}

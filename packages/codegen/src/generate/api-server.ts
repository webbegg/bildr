import type { ApiSource } from '../edit/api.ts'
import type { Model } from '../model/load.ts'
import { descriptionOf, inputFields, modelNames, namesOf, operationsOf, resultType, routeFile } from './api-model.ts'
import type { Emitted, InputField, Operation, SourceNames } from './api-model.ts'
import { importLine } from './imports.ts'
import { file, header, identifier, kebab, pascal, tsString } from './text.ts'

/**
 * The server runtime of the `api` data sources (SD-5, P2): the layer's Nuxt config, the client over `fetch`,
 * and per source its composition root (the only place where the use-cases meet the HTTP repository), one Nitro
 * route per query and action, and one client composable each. Sources with `runtime: 'browser'` are not
 * here: they have no server route (slice P3).
 */
export const generateApiRuntime = (model: Model, sources: ApiSource[]): Emitted[] => [
  layerConfigFile(),
  fetchClientFile(),
  queryHelpersFile(),
  ...sources.flatMap((source) => {
    const names = namesOf(model, source)
    return [
      rootFile(source, names),
      ...operationsOf(source).flatMap(operation => [routeFileOf(source, names, operation), composableFile(source, names, operation)])
    ]
  })
]

const layerConfigFile = (): Emitted => ({
  path: 'layers/apis/nuxt.config.ts',
  content: file([
    header('.bildr/datasources'),
    'import { fileURLToPath } from \'node:url\'',
    '',
    'const here = (path: string) => fileURLToPath(new URL(path, import.meta.url))',
    '',
    'export default defineNuxtConfig({',
    '  $meta: { name: \'apis\' },',
    '  // The composables of the API data sources live in app/composables/apis/ and are auto-imported.',
    '  imports: { dirs: [here(\'./app/composables/apis\')] }',
    '})'
  ])
})

/**
 * The HTTP client every server API source shares. It keeps the guards of the editor's remote fetches (node/remote.ts):
 * calls stay under the base URL, redirects are not followed, a timeout and a size cap. The secret is not here: the
 * composition root of each source puts it in `headers` from its own runtimeConfig.
 */
const fetchClientFile = (): Emitted => ({
  path: 'layers/apis/server/lib/fetch-client.ts',
  content: file([
    '// Generated by bildr. Editing this file detaches it from the editor.',
    '',
    '/** One call to an API data source. A `body` is sent as JSON; a `query` value left undefined is not sent. */',
    'export interface FetchRequest {',
    '  method: \'GET\' | \'POST\' | \'PUT\' | \'PATCH\' | \'DELETE\'',
    '  query?: Record<string, string | number | boolean | undefined>',
    '  body?: unknown',
    '}',
    '',
    '/** A call that failed. `status` is what the API answered, or 0 when it didn\'t; `message` finishes "The API …". */',
    'export class FetchFailure extends Error {',
    '  readonly status: number',
    '',
    '  constructor(status: number, message: string) {',
    '    super(message)',
    '    this.name = \'FetchFailure\'',
    '    this.status = status',
    '  }',
    '}',
    '',
    'const TIMEOUT_MS = 10_000',
    '// The cap of the editor\'s own remote fetches (node/remote.ts).',
    'const MAX_BYTES = 1_000_000',
    '',
    '/** The body of the answer as text, refusing one over MAX_BYTES (by its header, or as it arrives). */',
    'const readCapped = async (response: Response): Promise<string> => {',
    '  const tooBig = () => new FetchFailure(response.status, `answered more than ${MAX_BYTES / 1_000_000} MB`)',
    '  if (Number(response.headers.get(\'content-length\')) > MAX_BYTES) {',
    '    await response.body?.cancel()',
    '    throw tooBig()',
    '  }',
    '  const reader = response.body?.getReader()',
    '  if (!reader) return \'\'',
    '  const chunks: Uint8Array[] = []',
    '  let size = 0',
    '  for (;;) {',
    '    const { done, value } = await reader.read()',
    '    if (done) break',
    '    size += value.byteLength',
    '    if (size > MAX_BYTES) {',
    '      await reader.cancel()',
    '      throw tooBig()',
    '    }',
    '    chunks.push(value)',
    '  }',
    '  const bytes = new Uint8Array(size)',
    '  let offset = 0',
    '  for (const chunk of chunks) {',
    '    bytes.set(chunk, offset)',
    '    offset += chunk.byteLength',
    '  }',
    '  return new TextDecoder().decode(bytes)',
    '}',
    '',
    '/**',
    ' * A client over `fetch` for one API: the path is under `baseUrl` (a path that leaves it, or has a "." or ".." segment the URL would resolve, is refused), a redirect is',
    ' * not followed (it could leave the base URL, with the secret), and an answer is cut off after the timeout and the size cap.',
    ' * It answers the parsed JSON, or undefined for an empty answer.',
    ' */',
    'export const createFetchClient = ({ baseUrl, headers }: { baseUrl: string, headers: Record<string, string> }) => {',
    '  const base = new URL(baseUrl.endsWith(\'/\') ? baseUrl : `${baseUrl}/`)',
    '',
    '  return async (path: string, { method, query, body }: FetchRequest): Promise<unknown> => {',
    '    const relative = path.replace(/^\\//, \'\')',
    '    // A path parameter ".." (or "%2e%2e") would be resolved by the URL to another path of the API, called with the secret.',
    '    if (relative.split(\'/\').some(segment => /^(?:\\.|%2e){1,2}$/i.test(segment))) throw new FetchFailure(0, \'was asked for a path with a "." or ".." segment\')',
    '    const url = new URL(relative, base)',
    '    if (url.origin !== base.origin || url.pathname !== `${base.pathname}${relative}`) throw new FetchFailure(0, \'was asked for a path outside its base URL\')',
    '    for (const [key, value] of Object.entries(query ?? {})) {',
    '      if (value !== undefined) url.searchParams.set(key, String(value))',
    '    }',
    '    const signal = AbortSignal.timeout(TIMEOUT_MS)',
    '    const gone = () => new FetchFailure(0, signal.aborted ? `didn\'t answer within ${TIMEOUT_MS / 1000} s` : \'couldn\\\'t be reached\')',
    '    let response: Response',
    '    try {',
    '      response = await fetch(url, {',
    '        method,',
    '        headers: body === undefined ? headers : { ...headers, \'content-type\': \'application/json\' },',
    '        ...(body === undefined ? {} : { body: JSON.stringify(body) }),',
    '        redirect: \'manual\',',
    '        signal',
    '      })',
    '    } catch {',
    '      throw gone()',
    '    }',
    '    if (!response.ok) {',
    '      await response.body?.cancel()',
    '      throw new FetchFailure(response.status, response.status >= 300 && response.status < 400 ? `answered ${response.status}: a redirect is not followed` : `answered ${response.status}`)',
    '    }',
    '    let text: string',
    '    try {',
    '      text = await readCapped(response)',
    '    } catch (cause) {',
    '      throw cause instanceof FetchFailure ? cause : gone()',
    '    }',
    '    if (!text) return undefined',
    '    try {',
    '      return JSON.parse(text) as unknown',
    '    } catch {',
    '      throw new FetchFailure(response.status, \'answered without JSON\')',
    '    }',
    '  }',
    '}'
  ])
})

/** The two helpers the client composables share: a reactive query over the app's TanStack query client, and an async action. */
const queryHelpersFile = (): Emitted => ({
  path: 'layers/apis/app/data/api-query.ts',
  content: file([
    '// Generated by bildr. Editing this file detaches it from the editor.',
    'import { QueryObserver } from \'@tanstack/query-core\'',
    'import type { QueryObserverResult } from \'@tanstack/query-core\'',
    'import { getCurrentScope, onScopeDispose, shallowRef, toValue, watch } from \'vue\'',
    'import type { MaybeRefOrGetter } from \'vue\'',
    'import { err, ok } from \'#core/kernel/result\'',
    'import type { Result } from \'#core/kernel/result\'',
    'import { queryClient } from \'#layers/core/app/data/query-client\'',
    '',
    '/** What a query composable of an API data source gives `useApiQuery`. */',
    'export interface ApiQueryOptions<Input, Output> {',
    '  /** Where the answer is cached: the source and the query. The input is added to it. */',
    '  key: readonly unknown[]',
    '  input: MaybeRefOrGetter<Input>',
    '  fetch: (input: Input, signal: AbortSignal) => Promise<Output>',
    '}',
    '',
    '/** A query over the app\'s query client: `data`, `pending` and `error` are refs, and it fetches again when `input` changes. */',
    'export const useApiQuery = <Input, Output>({ key, input, fetch }: ApiQueryOptions<Input, Output>) => {',
    '  const optionsFor = () => {',
    '    const value = toValue(input)',
    '    return { queryKey: [...key, value], queryFn: ({ signal }: { signal: AbortSignal }) => fetch(value, signal) }',
    '  }',
    '  const observer = new QueryObserver<Output>(queryClient, optionsFor())',
    '  const data = shallowRef<Output>()',
    '  const error = shallowRef<string>()',
    '  const pending = shallowRef(true)',
    '  const sync = (result: QueryObserverResult<Output>) => {',
    '    data.value = result.data',
    '    error.value = result.error ? errorMessage(result.error) : undefined',
    '    pending.value = result.isFetching',
    '  }',
    '  sync(observer.getCurrentResult())',
    '  const unsubscribe = observer.subscribe(sync)',
    '  watch(() => toValue(input), () => observer.setOptions(optionsFor()), { deep: true })',
    '  if (getCurrentScope()) onScopeDispose(unsubscribe)',
    '  return { data, error, pending, refresh: () => observer.refetch() }',
    '}',
    '',
    '/** An action: `run` calls the API, then refetches the queries under `invalidates`. It answers a Result, never throws. */',
    'export const useApiAction = <Input, Output>(call: (input: Input) => Promise<Output>, invalidates: readonly unknown[]) => {',
    '  type RunArguments = undefined extends Input ? [input?: Input] : [input: Input]',
    '  const pending = shallowRef(false)',
    '  const error = shallowRef<string>()',
    '  const run = async (...[input]: RunArguments): Promise<Result<Output, string>> => {',
    '    pending.value = true',
    '    error.value = undefined',
    '    try {',
    '      const value = await call(input as Input)',
    '      await queryClient.invalidateQueries({ queryKey: invalidates })',
    '      return ok(value)',
    '    } catch (cause) {',
    '      const message = errorMessage(cause)',
    '      error.value = message',
    '      return err(message)',
    '    } finally {',
    '      pending.value = false',
    '    }',
    '  }',
    '  return { run, pending, error }',
    '}'
  ])
})

// ── Composition root ───────────────────────────────────────────────────

const STATUSES = ['remote_failed: 502', 'invalid_answer: 502', 'invalid_input: 400']

const rootFile = (source: ApiSource, names: SourceNames): Emitted => {
  const operations = operationsOf(source)
  const secret = source.auth ? identifier(source.auth.secret, `the secret of "${source.name}"`) : undefined
  // The settings are read as properties of `config`, never destructured: a secret named like a local (`headers`, `call`) or a reserved word is safe.
  const auth = source.auth?.type === 'header'
    ? `headers[${tsString(source.auth.header!)}] = config.${secret}`
    : `headers.authorization = \`Bearer \${config.${secret}}\``
  return {
    path: `layers/apis/server/utils/${names.dir}.ts`,
    source: names.source,
    content: file([
      header(names.source),
      `// Composition root of the "${source.name}" API: the only place where its use-cases meet the HTTP repository.`,
      'import { useRuntimeConfig } from \'nuxt/server\'',
      'import type { ErrorStatusMap } from \'#core/kernel/result\'',
      importLine(`../../shared/data/${names.dir}/client`, [{ name: 'ApiClient', type: true }]),
      importLine(`../../shared/data/${names.dir}/repositories/${names.adapterFile}`, [names.adapter]),
      importLine(`../../shared/domain/${names.dir}/errors`, [names.failure, 'remoteFailed']),
      ...operations
        .map(operation => ({ path: `../../shared/domain/${names.dir}/use-cases/${kebab(operation.name)}`, name: operation.name }))
        .sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0)
        .map(entry => importLine(entry.path, [entry.name])),
      importLine('../lib/fetch-client', ['createFetchClient', 'FetchFailure']),
      '',
      `/** The HTTP client of the "${source.name}" API: it calls the base URL of runtimeConfig.apis.${names.camel}, sending its secret there and nowhere else. */`,
      `const ${names.client} = (): ApiClient => {`,
      `  const config = useRuntimeConfig().apis.${names.camel}`,
      '  const headers: Record<string, string> = { accept: \'application/json\' }',
      ...(secret ? [`  if (config.${secret}) ${auth}`] : []),
      '  const call = createFetchClient({ baseUrl: config.baseUrl, headers })',
      '  return async (path, request) => {',
      '    try {',
      '      return await call(path, request)',
      '    } catch (cause) {',
      `      if (cause instanceof FetchFailure) throw new ${names.failure}(remoteFailed(cause.status, cause.message))`,
      '      throw cause',
      '    }',
      '  }',
      '}',
      '',
      `/** The use-cases of the "${source.name}" API, wired to its HTTP repository. */`,
      `export const ${names.root} = () => {`,
      `  const repository = ${names.adapter}(${names.client}())`,
      '  return {',
      operations.map(operation => `    ${operation.name}: ${operation.name}({ ${names.camel}: repository })`).join(',\n'),
      '  }',
      '}',
      '',
      `/** HTTP status of each "${source.name}" API error. */`,
      `export const ${names.status}: ErrorStatusMap = {`,
      STATUSES.map(status => `  ${status}`).join(',\n'),
      '}'
    ])
  }
}

// ── Routes ─────────────────────────────────────────────────────────────

const paramsOf = (fields: InputField[]) => fields.filter(field => !field.model)

/** `server/api/apis/<s>/<op>.<method>.ts`: reads the query string and the body, calls the use-case, answers or throws its error. */
const routeFileOf = (source: ApiSource, names: SourceNames, operation: Operation): Emitted => {
  const fields = inputFields(operation)
  const params = paramsOf(fields)
  const body = fields.find(field => field.model)
  const answers = !!operation.result
  const useEvent = fields.length > 0 || !answers
  // Parameters travel in the query string (path ones too: the route has no path segments), the body as JSON.
  const call = params.length && body ? '{ ...params, body }' : params.length ? 'input' : body ? '{ body }' : ''
  const use = `unwrapOrThrow(await ${names.root}().${operation.name}(${call}), ${names.status})`
  return {
    path: `layers/apis/server/api/apis/${names.dir}/${routeFile(operation)}`,
    source: names.source,
    content: file([
      header(names.source),
      importLine('nuxt/server', ['defineEventHandler', ...(params.length ? ['getValidatedQuery'] : []), ...(body ? ['readValidatedBody'] : []), ...(answers ? [] : ['setResponseStatus'])]),
      params.length > 0 && 'import { z } from \'zod\'',
      body && importLine(`../../../../shared/domain/${names.dir}/entities/${modelNames(body.model!).file}`, [modelNames(body.model!).schema]),
      importLine(`../../../utils/${names.dir}`, [names.root, names.status]),
      '',
      ...(params.length
        ? [
            `/** The parameters of "${operation.name}", read from the query string (everything arrives as text). */`,
            'const QuerySchema = z.object({',
            params.map(field => `  ${field.name}: ${field.query}`).join(',\n'),
            '})',
            ''
          ]
        : []),
      `export default defineEventHandler(async (${useEvent ? 'event' : ''}) => {`,
      ...(params.length ? [`  const ${body ? 'params' : 'input'} = await getValidatedQuery(event, QuerySchema)`] : []),
      ...(body ? [`  const body = await readValidatedBody(event, ${modelNames(body.model!).schema})`] : []),
      ...(answers
        ? [`  return ${use}`]
        : [`  ${use}`, '  setResponseStatus(event, 204)', '  return null']),
      '})'
    ])
  }
}

// ── Composables ────────────────────────────────────────────────────────

/** `app/composables/apis/use<S><Op>.ts`: a query is reactive data over the query client, an action an async `run`. */
const composableFile = (source: ApiSource, names: SourceNames, operation: Operation): Emitted => {
  const fields = inputFields(operation)
  const params = paramsOf(fields)
  const body = fields.find(field => field.model)
  const type = pascal(operation.name)
  const name = `use${names.pascal}${type}`
  const url = tsString(`/api/apis/${names.dir}/${kebab(operation.name)}`)
  const result = resultType(operation)
  const input = `${type}Input`
  const optionalInput = fields.every(field => field.optional)
  const about = descriptionOf(operation)
  const label = `${operation.kind === 'query' ? 'Query' : 'Action'} "${operation.name}" of the "${source.name}" API${about ? ` (${about})` : ''}`
  const lines = (...parts: Array<string | false>) => parts.filter((part): part is string => part !== false)
  const imports = lines(
    ...(operation.kind === 'query' && fields.length ? ['import type { MaybeRefOrGetter } from \'vue\''] : []),
    ...(operation.result ? [importLine(`../../../shared/domain/${names.dir}/entities/${modelNames(operation.result.model).file}`, [{ name: operation.result.model, type: true }])] : []),
    ...(fields.length ? [importLine(`../../../shared/domain/${names.dir}/use-cases/${kebab(operation.name)}`, [{ name: input, type: true }])] : []),
    importLine('../../data/api-query', [operation.kind === 'query' ? 'useApiQuery' : 'useApiAction'])
  )
  if (operation.kind === 'query') {
    const fetch = `$fetch<${result}>(${url}, { ${fields.length ? 'query, ' : ''}signal })`
    return {
      path: `layers/apis/app/composables/apis/${name}.ts`,
      source: names.source,
      content: file([
        header(names.source),
        ...imports,
        '',
        `/** ${label}: \`data\`, \`pending\` and \`error\` are refs${fields.length ? '; it fetches again when the input changes' : ''}. */`,
        `export const ${name} = (${fields.length ? `input: MaybeRefOrGetter<${input}>${optionalInput ? ' = {}' : ''}` : ''}) =>`,
        `  useApiQuery<${fields.length ? input : 'undefined'}, ${result}>({`,
        `    key: ['apis', ${tsString(names.dir)}, ${tsString(operation.name)}],`,
        `    input${fields.length ? '' : ': undefined'},`,
        `    fetch: (${fields.length ? 'query' : '_input'}, signal) => ${fetch}`,
        '  })'
      ])
    }
  }
  const request = [`method: ${tsString(operation.method)}`, ...(params.length ? ['query'] : []), ...(body ? ['body'] : [])].join(', ')
  const fetch = `$fetch<${result === 'void' ? 'unknown' : result}>(${url}, { ${request} })`
  const argument = params.length && body ? '{ body, ...query }' : body ? '{ body }' : params.length ? 'query' : ''
  // With a result both types are given; without one the output is the function's own (`void` can't be a type argument of a call).
  const generics = operation.result ? `<${fields.length ? input : 'undefined'}, ${result}>` : ''
  const call = operation.result ? `(${argument}) => ${fetch}` : `async (${argument}${fields.length ? `: ${input}` : ''}) => {\n      await ${fetch}\n    }`
  return {
    path: `layers/apis/app/composables/apis/${name}.ts`,
    source: names.source,
    content: file([
      header(names.source),
      ...imports,
      '',
      `/** ${label}: \`run(${fields.length ? 'input' : ''})\` calls the API, refetches the queries of the source and answers a Result. */`,
      `export const ${name} = () =>`,
      `  useApiAction${generics}(`,
      `    ${call},`,
      `    ['apis', ${tsString(names.dir)}]`,
      '  )'
    ])
  }
}

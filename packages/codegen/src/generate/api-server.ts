import type { ApiSource } from '../edit/api.ts'
import type { Model } from '../model/load.ts'
import { descriptionOf, inputFields, modelNames, namesOf, operationsOf, resultType, routeFile } from './api-model.ts'
import type { Emitted, InputField, Operation, SourceNames } from './api-model.ts'
import { importLine } from './imports.ts'
import { apiPaths, apisPaths, importPath } from './paths.ts'
import { clientOptions, FAILURE_ARGS, SOURCE_ERRORS } from './rest-source.ts'
import { file, header, identifier, kebab, pascal, tsString } from './text.ts'

/**
 * The runtime of the `api` data sources (SD-5). What every runtime shares: the layer's Nuxt config and the query
 * helpers the client composables are built on (`generateApiLayer`). The server runtime (P2): the client over `fetch`,
 * and per source its composition root (the only place where the use-cases meet the HTTP repository), one Nitro
 * route per query and action, and one client composable each (`generateServerRuntime`). The browser runtime is in
 * api-browser.ts: it has no server route, and its composables come from `composableFile` below.
 */
export const generateApiLayer = (): Emitted[] => [layerConfigFile(), queryHelpersFile()]

/** The server runtime of `sources`, which all have `runtime: 'server'`. */
export const generateServerRuntime = (model: Model, sources: ApiSource[]): Emitted[] => sources.flatMap((source) => {
  const names = namesOf(model, source)
  return [
    rootFile(source, names),
    ...operationsOf(source).flatMap(operation => [contractFileOf(source, names, operation), routeFileOf(source, names, operation), composableFile(source, names, operation)])
  ]
})

const layerConfigFile = (): Emitted => ({
  path: apisPaths.nuxtConfig,
  content: file([
    header('.bildr/datasources'),
    'import { fileURLToPath } from \'node:url\'',
    '',
    'const here = (path: string) => fileURLToPath(new URL(path, import.meta.url))',
    '',
    'export default defineNuxtConfig({',
    '  $meta: { name: \'apis\' },',
    '  // The composables of the API data sources live in app/composables/apis/ and are auto-imported.',
    '  imports: { dirs: [here(\'./app/composables/apis\')] }',
    '})'
  ])
})

/**
 * The helpers the client composables share: a query over the app's TanStack query client with the contract of Nuxt's useAsyncData
 * (`data`, `status`, `error`, `refresh`), and an action that answers a Result and refetches the source's queries. Both runtimes give them
 * a Result whose error is the source's own (`ApiError`): the page tells its errors apart by `type`. What every composable of the app
 * shares (`fromRoute`, `useAction`, the status) is the core's: layers/core/app/data/results.ts.
 */
const queryHelpersFile = (): Emitted => ({
  path: apisPaths.apiQuery,
  content: file([
    '// Generated by bildr. Editing this file detaches it from the editor.',
    'import { QueryObserver } from \'@tanstack/query-core\'',
    'import type { QueryObserverResult } from \'@tanstack/query-core\'',
    'import { getCurrentScope, onScopeDispose, shallowRef, toValue, watch } from \'vue\'',
    'import type { MaybeRefOrGetter } from \'vue\'',
    'import type { ApiError, DomainError, Result, SourceFailureType } from \'#core/kernel/result\'',
    'import { queryClient } from \'#layers/core/app/data/query-client\'',
    'import { Answered, failureOf, useAction } from \'#layers/core/app/data/results\'',
    'import type { DataStatus } from \'#layers/core/app/data/results\'',
    '',
    '/** What a query composable of an API data source gives `useApiQuery`. */',
    'export interface ApiQueryOptions<Input, Output, E extends DomainError> {',
    '  /** Where the answer is cached: the source and the query. The input is added to it. */',
    '  key: readonly unknown[]',
    '  input: MaybeRefOrGetter<Input>',
    '  /** The call: it answers a Result, never throws for an expected failure. */',
    '  fetch: (input: Input, signal: AbortSignal) => Promise<Result<Output, ApiError<E>>>',
    '}',
    '',

    '/** The failures of a source that may pass on a second try (SourceFailureType): it asked to wait, took too long, or is down. */',
    'const PASSING: ReadonlySet<string> = new Set<SourceFailureType>([\'rate_limited\', \'timeout\', \'unavailable\'])',
    '',
    '/**',
    ' * The longest wait a source may ask for (Retry-After) that the page waits out before trying again: a longer one shows the error. Three',
    ' * of them keep a query pending about half a minute at most.',
    ' */',
    'const MAX_WAIT_S = 10',
    '',
    '/** The seconds the source asked to wait, when it said (`retryAfter`, its Retry-After). */',
    'const waitOf = (cause: Error): number | undefined => {',
    '  const wait = cause instanceof Answered ? (cause.error as { retryAfter?: unknown }).retryAfter : undefined',
    '  return typeof wait === \'number\' ? wait : undefined',
    '}',
    '',
    '/**',
    ' * Only a call that may pass on a second try is tried again, three times at most: something unexpected (the server could not be',
    ' * reached), or a failure that passes (PASSING), unless it asked to wait longer than MAX_WAIT_S. What the API answered on purpose',
    ' * (a 404, a refusal) is its answer.',
    ' */',
    'const retry = (count: number, cause: Error) => {',
    '  if (count >= 3 || (waitOf(cause) ?? 0) > MAX_WAIT_S) return false',
    '  return !(cause instanceof Answered) || cause.error.type === \'unexpected\' || PASSING.has(cause.error.type)',
    '}',
    '',
    '/** How long before trying again: a backoff (1 s, 2 s, 4 s …, at most 30 s), or longer when the source asked to wait longer. */',
    'const retryDelay = (count: number, cause: Error) => Math.max(Math.min(1000 * 2 ** count, 30_000), (waitOf(cause) ?? 0) * 1000)',
    '',
    '/**',
    ' * A query over the app\'s query client, with the contract of Nuxt\'s useAsyncData: `data`, `status` and `error` (the source\'s typed',
    ' * error) are refs, `refresh()` fetches again. It also fetches again when `input` changes; after an error it is `pending` again.',
    ' */',
    'export const useApiQuery = <Input, Output, E extends DomainError>({ key, input, fetch }: ApiQueryOptions<Input, Output, E>) => {',
    '  const optionsFor = () => {',
    '    const value = toValue(input)',
    '    return {',
    '      queryKey: [...key, value],',
    '      queryFn: async ({ signal }: { signal: AbortSignal }) => {',
    '        const result = await fetch(value, signal)',
    '        if (!result.ok) throw new Answered(result.error)',
    '        return result.value',
    '      },',
    '      retry,',
    '      retryDelay',
    '    }',
    '  }',
    '  const observer = new QueryObserver<Output>(queryClient, optionsFor())',
    '  const data = shallowRef<Output>()',
    '  const status = shallowRef<DataStatus>(\'pending\')',
    '  const error = shallowRef<ApiError<E>>()',
    '  // The observer reports a failure on each update: it is read (and an unexpected one logged) once, and stays the same error.',
    '  let reported: Error | undefined',
    '  let failure: ApiError<E> | undefined',
    '  const errorOf = (cause: Error): ApiError<E> => {',
    '    if (cause !== reported || !failure) {',
    '      reported = cause',
    '      // What `fetch` answered is one of E: `Answered` carries it untyped through TanStack Query.',
    '      failure = failureOf<E>(cause)',
    '    }',
    '    return failure',
    '  }',
    '  const sync = (result: QueryObserverResult<Output>) => {',
    '    data.value = result.data',
    '    status.value = result.status === \'success\' ? \'success\' : result.isFetching || result.status === \'pending\' ? \'pending\' : \'error\'',
    '    error.value = status.value === \'error\' && result.error ? errorOf(result.error) : undefined',
    '  }',
    '  sync(observer.getCurrentResult())',
    '  const unsubscribe = observer.subscribe(sync)',
    '  watch(() => toValue(input), () => observer.setOptions(optionsFor()), { deep: true })',
    '  if (getCurrentScope()) onScopeDispose(unsubscribe)',
    '  const refresh = async () => {',
    '    await observer.refetch()',
    '  }',
    '  return { data, status, error, refresh }',
    '}',
    '',
    '/** An action (`useAction`: it answers a Result, never throws): `run` calls the API, then refetches the queries under `invalidates`. */',
    'export const useApiAction = <Input, Output, E extends DomainError>(call: (input: Input) => Promise<Result<Output, ApiError<E>>>, invalidates: readonly unknown[]) =>',
    '  useAction(async (...[input]: undefined extends Input ? [input?: Input] : [input: Input]) => {',
    '    const result = await call(input as Input)',
    '    if (result.ok) await queryClient.invalidateQueries({ queryKey: invalidates })',
    '    return result',
    '  })'
  ])
})

// ── Composition root ───────────────────────────────────────────────────

const STATUSES = [...SOURCE_ERRORS.map(error => `${error.type}: ${error.status}`), 'invalid_input: 400']
// A source with auth whose secret is not set is not ours to call: the server is not configured (503), never a bad gateway.
const NOT_CONFIGURED_STATUS = 'not_configured: 503'

const rootFile = (source: ApiSource, names: SourceNames): Emitted => {
  const operations = operationsOf(source)
  const secret = source.auth ? identifier(source.auth.secret, `the secret of "${source.name}"`) : undefined
  // The settings are read as properties of `config`, never destructured: a secret named like a local (`headers`, `call`) or a reserved word is safe.
  const auth = source.auth?.type === 'header'
    ? `headers[${tsString(source.auth.header!)}] = config.${secret}`
    : `headers.authorization = \`Bearer \${config.${secret}}\``
  // The env var the operator must set (a name, never the value). The model maps it; a hand-written file without it names the runtimeConfig key.
  const envVar = source.auth ? source.env?.[source.auth.secret] ?? `runtimeConfig.apis.${names.camel}.${secret}` : undefined
  const paths = apiPaths(names.dir)
  const path = paths.compositionRoot
  return {
    path,
    source: names.source,
    content: file([
      header(names.source),
      `// Composition root of the "${source.name}" API: the only place where its use-cases meet the HTTP repository.`,
      'import { useRuntimeConfig } from \'nuxt/server\'',
      importLine('#core/http/api-client', [{ name: 'ApiClient', type: true }, 'resultClient']),
      importLine('#core/http/client', ['createHttpClient']),
      importLine(importPath(path, paths.adapter(names.adapterFile)), [names.adapter]),
      importLine(importPath(path, paths.errors), [{ name: names.error, type: true }, 'remoteFailed']),
      ...operations
        .map(operation => ({ path: importPath(path, paths.useCase(operation.kind, kebab(operation.name))), name: operation.name }))
        .sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0)
        .map(entry => importLine(entry.path, [entry.name])),
      '',
      `/** The HTTP client of the "${source.name}" API: it calls the base URL of runtimeConfig.apis.${names.camel}, sending its secret there and nowhere else.${secret ? ' Without its secret it refuses the call.' : ''} */`,
      `const ${names.client} = (): ApiClient<${names.error}> => {`,
      `  const config = useRuntimeConfig().apis.${names.camel}`,
      '  const headers: Record<string, string> = { accept: \'application/json\' }',
      ...(secret ? [`  if (config.${secret}) ${auth}`] : []),
      // Nuxt reads an env var as JSON when it can (a numeric secret arrives as a number), hence the String().
      `  const call = createHttpClient({ baseUrl: config.baseUrl, headers${secret ? `, unconfigured: String(config.${secret} ?? '').trim() === ''` : ''}${clientOptions(source, true)} })`,
      ...(envVar
        ? [
            `  return resultClient(call, failure => failure.notConfigured`,
            `    ? { type: 'not_configured', message: ${tsString(`The "${source.name}" API is not configured: set ${envVar}`)} }`,
            `    : remoteFailed(${FAILURE_ARGS}))`
          ]
        : [`  return resultClient(call, failure => remoteFailed(${FAILURE_ARGS}))`]),
      '}',
      '',
      `/** The use-cases of the "${source.name}" API, wired to its HTTP repository. */`,
      `export const ${names.root} = () => {`,
      // A source whose operations answer nothing has no invalid answer to report: its repository takes no reporter.
      ...(operations.some(operation => operation.result)
        ? [
            '  // The detail of an answer that is not what the model says (field paths, expected types) stays in the server log: the error that reaches the browser has none.',
            `  const repository = ${names.adapter}(${names.client}(), detail => console.error(${tsString(`The "${source.name}" API answered something unexpected: `)} + detail))`
          ]
        : [`  const repository = ${names.adapter}(${names.client}())`]),
      '  return {',
      operations.map(operation => `    ${operation.name}: ${operation.name}({ ${names.camel}: repository })`).join(',\n'),
      '  }',
      '}',
      '',
      `/** HTTP status of each "${source.name}" API error. */`,
      `export const ${names.status} = {`,
      [...STATUSES, ...(envVar ? [NOT_CONFIGURED_STATUS] : [])].map(status => `  ${status}`).join(',\n'),
      `} satisfies Record<${names.error}['type'], number>`
    ])
  }
}

// ── Routes ─────────────────────────────────────────────────────────────

const paramsOf = (fields: InputField[]) => fields.filter(field => !field.model)

/** What a route of a server source and its composable import of its contract: `productsContract` and `ProductsResponse`. */
const contractNamesOf = (names: SourceNames, operation: Operation) => ({
  path: apiPaths(names.dir).contract(kebab(operation.name)),
  value: `${operation.name}Contract`,
  response: `${pascal(operation.name)}Response`
})

/** `import { type <Response>, <value> } from '…/shared/contracts/<s>/<op>'`, relative to `from`: what of it `from` uses. */
const contractImport = (from: string, names: SourceNames, operation: Operation, uses: { response: boolean, value: boolean }) => {
  const contract = contractNamesOf(names, operation)
  const entries = [...(uses.response ? [{ name: contract.response, type: true }] : []), ...(uses.value ? [contract.value] : [])]
  return entries.length > 0 && importLine(importPath(from, contract.path), entries)
}

/**
 * `shared/contracts/<s>/<op>.ts` (codegen-architecture R2): the HTTP contract of a route of a server source, as a module's (T4b): its
 * method, its path, the schema of its query string (as text, coerced) and of its body, and the type of its answer. The route validates
 * with it and declares its answer as it; the composable calls its path with its method and reads its answer as it.
 */
const contractFileOf = (source: ApiSource, names: SourceNames, operation: Operation): Emitted => {
  const fields = inputFields(operation)
  const params = paramsOf(fields)
  const body = fields.find(field => field.model)
  const contract = contractNamesOf(names, operation)
  const paths = apiPaths(names.dir)
  // What it imports of each model of the source: the result's type, the body's schema; one line per model.
  const models = new Map<string, Array<{ name: string, type?: boolean }>>()
  const add = (model: string, entry: { name: string, type?: boolean }) => models.set(model, [...(models.get(model) ?? []), entry])
  if (operation.result) add(operation.result.model, { name: operation.result.model, type: true })
  if (body) add(body.model!, { name: modelNames(body.model!).schema })
  const imported = [...models.values()].flat().map(entry => entry.name)
  if (imported.includes(contract.response)) {
    throw new Error(`${names.source}: the contract's response type ${contract.response} would take the name of the ${contract.response} it answers: rename the operation "${operation.name}" or the model`)
  }
  return {
    path: contract.path,
    source: names.source,
    content: file([
      header(names.source),
      params.length > 0 && 'import { z } from \'zod\'',
      ...[...models.entries()]
        .map(([model, entries]) => importLine(importPath(contract.path, paths.entity(modelNames(model).file)), entries))
        .sort(),
      '',
      `/** The HTTP contract of the ${operation.kind} "${operation.name}" of the "${source.name}" API: its route and its composable both read it. */`,
      `export const ${contract.value} = {`,
      [
        `  method: ${tsString(operation.method)}`,
        // Parameters travel in the query string (path ones too: the route has no path segments), the body as JSON.
        `  path: ${tsString(`/api/apis/${names.dir}/${kebab(operation.name)}`)}`,
        ...(params.length
          ? [[
              '  /** Its parameters, read from the query string (everything arrives as text). */',
              '  query: z.object({',
              params.map(field => `    ${field.name}: ${field.query}`).join(',\n'),
              '  })'
            ].join('\n')]
          : []),
        ...(body ? [`  body: ${modelNames(body.model!).schema}`] : [])
      ].join(',\n'),
      '} as const',
      '',
      '/** What the route answers. */',
      // An action that answers nothing answers the route's empty answer (204): `undefined`, as its composable reads it.
      `export type ${contract.response} = ${resultType(operation)}`
    ])
  }
}

/** `server/api/apis/<s>/<op>.<method>.ts`: reads the query string and the body as its contract says, calls the use-case, answers or throws its error. */
const routeFileOf = (source: ApiSource, names: SourceNames, operation: Operation): Emitted => {
  const fields = inputFields(operation)
  const params = paramsOf(fields)
  const body = fields.find(field => field.model)
  const answers = !!operation.result
  const call = params.length && body ? '{ ...params, body }' : params.length ? 'input' : body ? '{ body }' : ''
  // The event also answers the API's Retry-After (R3'b).
  const use = `unwrapOrThrow(await ${names.root}().${operation.name}(${call}), ${names.status}, event)`
  const paths = apiPaths(names.dir)
  const path = paths.apiRoute(routeFile(operation))
  const contract = contractNamesOf(names, operation)
  return {
    path,
    source: names.source,
    content: file([
      header(names.source),
      importLine('nuxt/server', ['defineEventHandler', ...(params.length ? ['getValidatedQuery'] : []), ...(body ? ['readValidatedBody'] : []), ...(answers ? [] : ['setResponseStatus'])]),
      contractImport(path, names, operation, { response: answers, value: fields.length > 0 }),
      importLine(importPath(path, paths.compositionRoot), [names.root, names.status]),
      '',
      // A route that answers nothing answers null (204), not its contract's `undefined`: its answer is not declared.
      `export default defineEventHandler(async (event)${answers ? `: Promise<${contract.response}>` : ''} => {`,
      ...(params.length ? [`  const ${body ? 'params' : 'input'} = await getValidatedQuery(event, ${contract.value}.query)`] : []),
      ...(body ? [`  const body = await readValidatedBody(event, ${contract.value}.body)`] : []),
      ...(answers
        ? [`  return ${use}`]
        : [`  ${use}`, '  setResponseStatus(event, 204)', '  return null']),
      '})'
    ])
  }
}

// ── Composables ────────────────────────────────────────────────────────

/**
 * `app/composables/apis/use<S><Op>.ts`: a query is `{ data, status, error, refresh }` over the query client, an action an async `run`. The
 * public signature is the same for both runtimes, its error the source's own; only what is called differs: a server source calls its Nitro
 * route (`fromRoute` reads it as a Result), a browser one the use-case itself (through the composition of app/data/<s>.ts), which answers
 * one. A query passes the AbortSignal of its fetch to the composition, so a cancelled query cancels its request, as the `$fetch` of a
 * server one does.
 */
export const composableFile = (source: ApiSource, names: SourceNames, operation: Operation, runtime: ApiSource['runtime'] = 'server'): Emitted => {
  const browser = runtime === 'browser'
  const fields = inputFields(operation)
  const params = paramsOf(fields)
  const body = fields.find(field => field.model)
  const type = pascal(operation.name)
  const name = `use${names.pascal}${type}`
  const contract = contractNamesOf(names, operation)
  // A server source's composable reads its route's answer as the contract says; a browser one has no route, the use-case answers.
  const result = browser ? resultType(operation) : contract.response
  const input = `${type}Input`
  // The type arguments of useApiQuery / useApiAction: what it takes, what it answers, the source's error.
  const generics = `<${fields.length ? input : 'undefined'}, ${result}, ${names.error}>`
  const optionalInput = fields.every(field => field.optional)
  const about = descriptionOf(operation)
  const label = `${operation.kind === 'query' ? 'Query' : 'Action'} "${operation.name}" of the "${source.name}" API${about ? ` (${about})` : ''}`
  const lines = (...parts: Array<string | false>) => parts.filter((part): part is string => part !== false)
  const paths = apiPaths(names.dir)
  const path = apisPaths.composable(name)
  const imports = lines(
    ...(operation.kind === 'query' && fields.length ? ['import type { MaybeRefOrGetter } from \'vue\''] : []),
    ...(browser ? [] : ['import { fromRoute } from \'#layers/core/app/data/results\'']),
    ...(browser
      ? operation.result ? [importLine(importPath(path, paths.entity(modelNames(operation.result.model).file)), [{ name: operation.result.model, type: true }])] : []
      : [contractImport(path, names, operation, { response: true, value: true })]),
    importLine(importPath(path, paths.errors), [{ name: names.error, type: true }]),
    ...(fields.length ? [importLine(importPath(path, paths.useCase(operation.kind, kebab(operation.name))), [{ name: input, type: true }])] : []),
    importLine(importPath(path, apisPaths.apiQuery), [operation.kind === 'query' ? 'useApiQuery' : 'useApiAction']),
    ...(browser ? [importLine(importPath(path, paths.browserRoot), [names.root])] : [])
  )
  const queryDoc = `/** ${label}: \`data\`, \`status\` and \`error\` are refs, \`refresh()\` fetches again${fields.length ? '; it also fetches again when the input changes' : ''}.`
  // The local the browser composables hold the composition in: `api(signal)` gives the use-cases bound to that call's signal.
  const use = 'api'
  if (operation.kind === 'query' && browser) {
    return {
      path,
      source: names.source,
      content: file([
        header(names.source),
        ...imports,
        '',
        `${queryDoc} It calls the API from the page, through the use-case. */`,
        `export const ${name} = (${fields.length ? `input: MaybeRefOrGetter<${input}>${optionalInput ? ' = {}' : ''}` : ''}) => {`,
        `  const ${use} = ${names.root}()`,
        `  return useApiQuery${generics}({`,
        `    key: ['apis', ${tsString(names.dir)}, ${tsString(operation.name)}],`,
        `    input${fields.length ? '' : ': undefined'},`,
        `    fetch: (${fields.length ? 'query' : '_input'}, signal) => ${use}(signal).${operation.name}(${fields.length ? 'query' : ''})`,
        '  })',
        '}'
      ])
    }
  }
  if (operation.kind === 'query') {
    const fetch = `fromRoute($fetch<${result}>(${contract.value}.path, { method: ${contract.value}.method, ${fields.length ? 'query, ' : ''}signal }))`
    return {
      path,
      source: names.source,
      content: file([
        header(names.source),
        ...imports,
        '',
        `${queryDoc} */`,
        `export const ${name} = (${fields.length ? `input: MaybeRefOrGetter<${input}>${optionalInput ? ' = {}' : ''}` : ''}) =>`,
        `  useApiQuery${generics}({`,
        `    key: ['apis', ${tsString(names.dir)}, ${tsString(operation.name)}],`,
        `    input${fields.length ? '' : ': undefined'},`,
        `    fetch: (${fields.length ? 'query' : '_input'}, signal) => ${fetch}`,
        '  })'
      ])
    }
  }
  if (browser) {
    return {
      path,
      source: names.source,
      content: file([
        header(names.source),
        ...imports,
        '',
        `/** ${label}: \`run(${fields.length ? 'input' : ''})\` calls the API from the page, through the use-case, refetches the queries of the source and answers a Result. */`,
        `export const ${name} = () => {`,
        `  const ${use} = ${names.root}()`,
        `  return useApiAction${generics}(`,
        `    ${fields.length ? 'input' : '()'} => ${use}().${operation.name}(${fields.length ? 'input' : ''}),`,
        `    ['apis', ${tsString(names.dir)}]`,
        '  )',
        '}'
      ])
    }
  }
  const request = [`method: ${contract.value}.method`, ...(params.length ? ['query'] : []), ...(body ? ['body'] : [])].join(', ')
  // An action that answers nothing gets the route's empty answer (204): `undefined`, as its contract says.
  const fetch = `fromRoute($fetch<${result}>(${contract.value}.path, { ${request} }))`
  const argument = params.length && body ? '{ body, ...query }' : body ? '{ body }' : params.length ? 'query' : ''
  const call = `${argument === 'query' ? argument : `(${argument})`} => ${fetch}`
  return {
    path,
    source: names.source,
    content: file([
      header(names.source),
      ...imports,
      '',
      `/** ${label}: \`run(${fields.length ? 'input' : ''})\` calls the API, refetches the queries of the source and answers a Result. */`,
      `export const ${name} = () =>`,
      `  useApiAction${generics}(`,
      `    ${call},`,
      `    ['apis', ${tsString(names.dir)}]`,
      '  )'
    ])
  }
}

/**
 * The HTTP client every server API source shares. It keeps the guards of the editor's remote fetches (node/remote.ts):
 * calls stay under the base URL, redirects are not followed, a timeout and a size cap. The secret is not here: the
 * composition root of each source puts it in `headers` from its own runtimeConfig.
 */
const fetchClientFile = (): Emitted => ({
  path: 'layers/apis/server/lib/fetch-client.ts',
  content: file([
    '// Generated by bildr. Editing this file detaches it from the editor.',
    '',
    '/** One call to an API data source. A `body` is sent as JSON; a `query` value left undefined is not sent. */',
    'export interface FetchRequest {',
    '  method: \'GET\' | \'POST\' | \'PUT\' | \'PATCH\' | \'DELETE\'',
    '  query?: Record<string, string | number | boolean | undefined>',
    '  body?: unknown',
    '}',
    '',
    '/**',
    ' * A call that failed. `status` is what the API answered, or 0 when it didn\'t; `message` finishes "The API …".',
    ' * `notConfigured` is a call that was refused before it was sent: the source has auth and its secret is not set.',
    ' */',
    'export class FetchFailure extends Error {',
    '  readonly status: number',
    '  readonly notConfigured: boolean',
    '',
    '  constructor(status: number, message: string, notConfigured = false) {',
    '    super(message)',
    '    this.name = \'FetchFailure\'',
    '    this.status = status',
    '    this.notConfigured = notConfigured',
    '  }',
    '}',
    '',
    'const TIMEOUT_MS = 10_000',
    '// The cap of the editor\'s own remote fetches (node/remote.ts).',
    'const MAX_BYTES = 1_000_000',
    '',
    '/** The body of the answer as text, refusing one over MAX_BYTES (by its header, or as it arrives). */',
    'const readCapped = async (response: Response): Promise<string> => {',
    '  const tooBig = () => new FetchFailure(response.status, `answered more than ${MAX_BYTES / 1_000_000} MB`)',
    '  if (Number(response.headers.get(\'content-length\')) > MAX_BYTES) {',
    '    await response.body?.cancel()',
    '    throw tooBig()',
    '  }',
    '  const reader = response.body?.getReader()',
    '  if (!reader) return \'\'',
    '  const chunks: Uint8Array[] = []',
    '  let size = 0',
    '  for (;;) {',
    '    const { done, value } = await reader.read()',
    '    if (done) break',
    '    size += value.byteLength',
    '    if (size > MAX_BYTES) {',
    '      await reader.cancel()',
    '      throw tooBig()',
    '    }',
    '    chunks.push(value)',
    '  }',
    '  const bytes = new Uint8Array(size)',
    '  let offset = 0',
    '  for (const chunk of chunks) {',
    '    bytes.set(chunk, offset)',
    '    offset += chunk.byteLength',
    '  }',
    '  return new TextDecoder().decode(bytes)',
    '}',
    '',
    '/**',
    ' * A client over `fetch` for one API: the path is under `baseUrl` (a path that leaves it, or has a "." or ".." segment the URL would resolve, is refused), a redirect is',
    ' * not followed (it could leave the base URL, with the secret), and an answer is cut off after the timeout and the size cap.',
    ' * `unconfigured` is a source with auth whose secret is not set: every call is refused before it is sent (never without credentials).',
    ' * It answers the parsed JSON, or undefined for an empty answer.',
    ' */',
    'export const createFetchClient = ({ baseUrl, headers, unconfigured = false }: { baseUrl: string, headers: Record<string, string>, unconfigured?: boolean }) => {',
    '  const base = new URL(baseUrl.endsWith(\'/\') ? baseUrl : `${baseUrl}/`)',
    '',
    '  return async (path: string, { method, query, body }: FetchRequest): Promise<unknown> => {',
    '    if (unconfigured) throw new FetchFailure(0, \'has no secret set, so it was not called\', true)',
    '    const relative = path.replace(/^\\//, \'\')',
    '    // A path parameter ".." (or "%2e%2e") would be resolved by the URL to another path of the API, called with the secret.',
    '    if (relative.split(\'/\').some(segment => /^(?:\\.|%2e){1,2}$/i.test(segment))) throw new FetchFailure(0, \'was asked for a path with a "." or ".." segment\')',
    '    const url = new URL(relative, base)',
    '    if (url.origin !== base.origin || url.pathname !== `${base.pathname}${relative}`) throw new FetchFailure(0, \'was asked for a path outside its base URL\')',
    '    for (const [key, value] of Object.entries(query ?? {})) {',
    '      if (value !== undefined) url.searchParams.set(key, String(value))',
    '    }',
    '    const signal = AbortSignal.timeout(TIMEOUT_MS)',
    '    const gone = () => new FetchFailure(0, signal.aborted ? `didn\'t answer within ${TIMEOUT_MS / 1000} s` : \'couldn\\\'t be reached\')',
    '    let response: Response',
    '    try {',
    '      response = await fetch(url, {',
    '        method,',
    '        headers: body === undefined ? headers : { ...headers, \'content-type\': \'application/json\' },',
    '        ...(body === undefined ? {} : { body: JSON.stringify(body) }),',
    '        redirect: \'manual\',',
    '        signal',
    '      })',
    '    } catch {',
    '      throw gone()',
    '    }',
    '    if (!response.ok) {',
    '      await response.body?.cancel()',
    '      throw new FetchFailure(response.status, response.status >= 300 && response.status < 400 ? `answered ${response.status}: a redirect is not followed` : `answered ${response.status}`)',
    '    }',
    '    let text: string',
    '    try {',
    '      text = await readCapped(response)',
    '    } catch (cause) {',
    '      throw cause instanceof FetchFailure ? cause : gone()',
    '    }',
    '    if (!text) return undefined',
    '    try {',
    '      return JSON.parse(text) as unknown',
    '    } catch {',
    '      throw new FetchFailure(response.status, \'answered without JSON\')',
    '    }',
    '  }',
    '}'
  ])
})


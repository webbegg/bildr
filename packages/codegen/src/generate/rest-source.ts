import type { DataSourceFile, RepositoryFile } from '../model/schemas.ts'
import { datasourceOf, repositoryOf } from './context.ts'
import type { ModuleContext } from './context.ts'
import { camel, file, kebab, pascal, tsString } from './text.ts'

/**
 * A module's REST data sources, read the way the apis layer reads an API (codegen-architecture R1'): the port of a repository on one
 * answers a Result, its adapter validates the answer and maps it to the domain, and a failure is the source's typed error, never a
 * throw. A list-only repository goes first; one that also looks up and writes still throws through core's useRemote.
 */
export const answersResult = (context: ModuleContext, repository: RepositoryFile) =>
  datasourceOf(context, repository).kind === 'rest' && repository.operations.every(op => op === 'list')

/** The REST sources the module's Result-answering repositories read, by name. */
export const resultSources = (context: ModuleContext): DataSourceFile[] => {
  const sources = new Map<string, DataSourceFile>()
  for (const entity of context.module.entities) {
    const repository = repositoryOf(context, entity)
    if (repository && answersResult(context, repository)) sources.set(repository.datasource, datasourceOf(context, repository))
  }
  return [...sources.values()].sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)
}

/** The names a REST source's errors and client go by in a module. */
export const sourceNames = (context: ModuleContext, source: DataSourceFile) => ({
  error: `${pascal(source.name)}SourceError`,
  failed: `${camel(source.name)}Failed`,
  invalidAnswer: `${camel(source.name)}InvalidAnswer`,
  client: `${camel(source.name)}Client`,
  file: kebab(source.name),
  from: `#${context.name}/domain/sources/${kebab(source.name)}`
})

/** Every error a REST source's call can answer, with its HTTP status: what it answered is not the app's to fix (502). */
export const SOURCE_ERRORS = [{ type: 'remote_failed', status: 502 }, { type: 'invalid_answer', status: 502 }] as const

/** Refuses an action error typed like a source's: the module's union would have one type in two shapes. */
export const checkSourceErrorTypes = (context: ModuleContext, types: string[]) => {
  const source = resultSources(context)[0]
  const taken = types.find(type => SOURCE_ERRORS.some(error => error.type === type))
  if (source && taken) throw new Error(`${context.name}: the error type "${taken}" is the "${source.name}" data source's: name it another way`)
}

const sourceFile = (context: ModuleContext, source: DataSourceFile) => context.model.paths[source.id] ?? `.bildr/datasources/${source.name}.json`

/** `shared/domain/sources/<source>.ts`: what a call to the source can fail with, and the factories of each failure. */
export const sourceErrorsFile = (context: ModuleContext, source: DataSourceFile) => {
  const names = sourceNames(context, source)
  const from = sourceFile(context, source)
  return {
    path: context.paths.sourceErrors(names.file),
    source: from,
    content: file([
      `// Generated by bildr from ${from}. Editing this file detaches it from the editor.`,
      '',
      `/** Every expected failure of a call to the "${source.name}" REST data source: it answered with an error, or it answered something unexpected. */`,
      `export type ${names.error} =`,
      '  | { type: \'remote_failed\', message: string, status: number }',
      '  | { type: \'invalid_answer\', message: string }',
      '',
      `/** \`status\` is what the source answered, or 0 when it didn't answer; \`detail\` finishes "The "${source.name}" data source …". */`,
      `export const ${names.failed} = (status: number, detail: string): ${names.error} => ({ type: 'remote_failed', message: \`The "${source.name}" data source \${detail}.\`, status })`,
      '',
      '/** The answer is not what the model says. The error has no detail: it reaches the browser, and the detail (field paths, what was expected) is for the server log. */',
      `export const ${names.invalidAnswer} = (): ${names.error} => ({ type: 'invalid_answer', message: ${tsString(`The "${source.name}" data source answered something unexpected`)} })`
    ])
  }
}

/** The client of a REST source in its module's composition root: base URL and secret from runtimeConfig (env), the secret sent there only. */
export const sourceClientLines = (context: ModuleContext, source: DataSourceFile): string[] => {
  const names = sourceNames(context, source)
  const config = /^[A-Za-z_$][\w$]*$/.test(source.name) ? `useRuntimeConfig().datasources.${source.name}` : `useRuntimeConfig().datasources[${tsString(source.name)}]`
  return [
    `/** The client of the "${source.name}" REST data source: its base URL and secret come from runtimeConfig.datasources (env), and the secret is sent there only. */`,
    `const ${names.client} = (): ApiClient<${names.error}> => {`,
    `  const { baseUrl, apiKey } = ${config}`,
    '  const headers: Record<string, string> = { accept: \'application/json\' }',
    '  if (apiKey) headers.authorization = `Bearer ${apiKey}`',
    `  return resultClient(createHttpClient({ baseUrl, headers }), failure => ${names.failed}(failure.status, failure.message))`,
    '}'
  ]
}

/** The repository wired to its source's client, an invalid answer's detail logged on the server (the error that reaches the browser has none). */
export const sourceAdapterArgs = (context: ModuleContext, source: DataSourceFile) =>
  `${sourceNames(context, source).client}(), detail => console.error(${tsString(`The "${source.name}" data source answered something unexpected: `)} + detail)`

import { tsString } from '../text.ts'

// ── Markup helpers ──────────────────────────────────────────────────────

/** Line terminators other than \n become character references, so a model value never splits or reflows generated lines. */
export const LINE_TERMINATORS = new RegExp(`[\r${String.fromCharCode(0x2028)}${String.fromCharCode(0x2029)}]`, 'g')

export const escapeLines = (text: string) => text.replace(LINE_TERMINATORS, char => `&#${char.charCodeAt(0)};`)

export const escapeText = (text: string) => escapeLines(text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{\{/g, '&#123;&#123;'))

export const escapeAttr = (text: string) => escapeLines(text.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;'))

/** Directive order of eslint-plugin-vue's attributes-order. */
export const ORDER = { for: 0, if: 1, key: 2, model: 3, attr: 4, event: 5 } as const

export type Attr = { kind: keyof typeof ORDER, text: string }

export const attr = (kind: Attr['kind'], text: string): Attr => ({ kind, text })

export const staticAttr = (name: string, value: string) => attr('attr', `${name}="${escapeAttr(value)}"`)

export const boundAttr = (name: string, code: string) => attr('attr', `:${name}="${escapeAttr(code)}"`)

export const openTag = (tag: string, attrs: Attr[]) => {
  const sorted = attrs.map((entry, index) => ({ entry, index })).sort((a, b) => ORDER[a.entry.kind] - ORDER[b.entry.kind] || a.index - b.index)
  return [tag, ...sorted.map(({ entry }) => entry.text)].join(' ')
}

/** HTML void elements: never closed (`<img …>`). */
export const VOID_TAGS = ['img']

/** An element: self-closed when empty, one line for text, nested lines otherwise. */
export const element = (tag: string, attrs: Attr[], inner: string | string[] | undefined, indent: string): string[] => {
  const open = openTag(tag, attrs)
  if (VOID_TAGS.includes(tag)) return [`${indent}<${open}>`]
  if (inner === undefined || (Array.isArray(inner) && !inner.length)) return [`${indent}<${open} />`]
  if (typeof inner === 'string') return [`${indent}<${open}>${inner}</${tag}>`]
  return [`${indent}<${open}>`, ...inner, `${indent}</${tag}>`]
}

/**
 * A string literal for an interpolation (`{{ 'a\nb' }}`): `tsString`, with the characters that could end the
 * interpolation or open a tag written as escapes, so the template parser never sees them.
 */
export const interpolatedString = (text: string) => tsString(text).replace(/[<>&{}]/g, char => `\\u${char.charCodeAt(0).toString(16).padStart(4, '0')}`)

/**
 * Static text in a template. Vue condenses whitespace in template text (a newline becomes a space), so text with
 * a line break, which the canvas keeps (`whitespace-pre-line`), goes out as a string expression instead.
 */
export const staticText = (text: string) => text.includes('\n') ? `{{ ${interpolatedString(text)} }}` : escapeText(text)

// ── The SFC ─────────────────────────────────────────────────────────────

export const vueHeader = (source: string) => `<!-- Generated by bildr from ${source}. Editing this file detaches it from the editor; prefer overriding it from the root app/. -->`

export const sfc = (source: string, script: string[], template: string[]) => [
  vueHeader(source),
  ...(script.length ? ['<script setup lang="ts">', ...script, '</script>', ''] : []),
  '<template>',
  ...template,
  '</template>',
  ''
].join('\n')

/** Text helpers shared by the emitters. Everything that comes from the model goes through an escaper. */

export const header = (source: string) => `// Generated by bildr from ${source}. Editing this file detaches it from the editor.`

const LINE_SEPARATOR = String.fromCharCode(0x2028)
const PARAGRAPH_SEPARATOR = String.fromCharCode(0x2029)

/** A single-quoted TS string literal, safe in .ts files and SFC scripts. */
export const tsString = (value: string) => `'${value
  .replace(/\\/g, '\\\\')
  .replace(/'/g, '\\\'')
  .replace(/\n/g, '\\n')
  .replace(/\r/g, '\\r')
  .replaceAll(LINE_SEPARATOR, '\\u2028')
  .replaceAll(PARAGRAPH_SEPARATOR, '\\u2029')
  .replace(/<\//g, '<\\/')}'`

/** Text inside a `/** … *\/` comment: no comment terminators, no line breaks. */
const LINE_BREAKS = new RegExp(`[\\r\\n${LINE_SEPARATOR}${PARAGRAPH_SEPARATOR}]+`, 'g')
export const docText = (value: string) => value.replace(/\*\//g, '*\\/').replace(LINE_BREAKS, ' ')

/** A regex literal body; `/` is escaped so the literal can't end early. */
export const regexLiteral = (pattern: string) => `/${pattern.replace(/(?<!\\)\//g, '\\/')}/`

const IDENTIFIER = /^[A-Za-z_$][\w$]*$/

/** A TS object/array literal for JSON data (seeds): unquoted keys where possible, single-quoted strings, two-space indent. */
export const tsLiteral = (value: unknown, indent = ''): string => {
  if (value === null) return 'null'
  if (typeof value === 'string') return tsString(value)
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  const inner = `${indent}  `
  if (Array.isArray(value)) {
    if (!value.length) return '[]'
    return `[\n${value.map(item => `${inner}${tsLiteral(item, inner)}`).join(',\n')}\n${indent}]`
  }
  const entries = Object.entries(value as Record<string, unknown>)
  if (!entries.length) return '{}'
  return `{\n${entries.map(([key, item]) => `${inner}${IDENTIFIER.test(key) ? key : tsString(key)}: ${tsLiteral(item, inner)}`).join(',\n')}\n${indent}}`
}

/** `5 * 60_000` for whole minutes, `1_500` style otherwise. */
export const tsDuration = (ms: number) => ms >= 60_000 && ms % 60_000 === 0
  ? `${ms / 60_000} * 60_000`
  : String(ms).replace(/\B(?=(\d{3})+(?!\d))/g, '_')

export const pascal = (name: string) => name.split(/[-_\s]+/).filter(Boolean).map(part => part.charAt(0).toUpperCase() + part.slice(1)).join('')
export const camel = (name: string) => {
  const value = pascal(name)
  return value.charAt(0).toLowerCase() + value.slice(1)
}
export const kebab = (name: string) => name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[_\s]+/g, '-').toLowerCase()
export const snake = (name: string) => kebab(name).replace(/-/g, '_')

/** Lines joined with newlines, plus the trailing newline every generated file ends with. */
export const file = (lines: Array<string | false | undefined>) => `${lines.filter(line => line !== false && line !== undefined).join('\n')}\n`

import { DEFAULT_THEME, PALETTE_NAMES, THEME_COLORS, themeCss } from '../design/theme.ts'
import type { Theme } from '../design/theme.ts'
import type { Model } from '../model/load.ts'
import type { DataSourceFile } from '../model/schemas.ts'
import type { GeneratedFile } from '../sync/plan.ts'
import { apiSources, browserApiSources, isCallable, serverApiSources } from './api-model.ts'
import { apisPaths, corePaths, modulePaths } from './paths.ts'
import { camel, file, header, tsString } from './text.ts'

/**
 * The project-level files of the core layer (T7b): the theme stylesheet, the
 * app config (site and Nuxt UI colours) and the core Nuxt config (database
 * and data source runtimeConfig). Pure and deterministic.
 */
export const generateProject = (model: Model): GeneratedFile[] => {
  const { $schema: _, ...theme } = model.theme ?? DEFAULT_THEME as Theme & { $schema?: string }
  return [appConfigFile(model, theme), themeFile(theme), nuxtConfigFile(model), vitestConfigFile(model)]
}

/** The root vitest config: unit and API projects, with every layer alias mirrored (vitest doesn't read nuxt.config). */
const vitestConfigFile = (model: Model): GeneratedFile => {
  const apiTests = apiSources(model).some(isCallable) ? `, '${apisPaths.testGlob}'` : ''
  return {
    path: 'vitest.config.ts',
    owner: 'managed',
    content: file([
      '// Generated by bildr. Editing this file detaches it from the editor.',
      'import { fileURLToPath } from \'node:url\'',
      'import { defineConfig } from \'vitest/config\'',
      '',
      'const here = (path: string) => fileURLToPath(new URL(path, import.meta.url))',
      '',
      '// Use-case and adapter tests run in plain Node (no Nuxt). API tests boot the built app with @nuxt/test-utils.',
      '// The aliases mirror the ones the layers declare in their nuxt.config.ts.',
      'export default defineConfig({',
      '  resolve: {',
      '    alias: {',
      [`      '#core': here('./${corePaths.shared}')`, ...Object.keys(model.modules).sort().flatMap(name => [
        `      '#${name}/contracts': here('./${modulePaths(name).contracts}')`,
        `      '#${name}/domain': here('./${modulePaths(name).domain}')`
      ])].join(',\n'),
      '    }',
      '  },',
      '  test: {',
      '    passWithNoTests: true,',
      '    projects: [',
      // The tests of the API data sources (layers/apis/test/<source>/) run with the unit ones.
      `      { extends: true, test: { name: 'unit', include: ['layers/*/test/{application,infrastructure}/**/*.test.ts'${apiTests}] } },`,
      '      { extends: true, test: { name: \'api\', include: [\'layers/*/test/api/**/*.test.ts\'], testTimeout: 120_000, hookTimeout: 300_000 } }',
      '    ]',
      '  }',
      '})'
    ])
  }
}

const themeFile = (theme: Theme): GeneratedFile => ({
  path: corePaths.themeCss,
  owner: 'managed',
  source: '.bildr/theme.json',
  // themeCss is the stylesheet the editor canvas paints with, so the app looks the same.
  content: [
    '/* Generated by bildr from .bildr/theme.json. Editing this file detaches it from the editor. */',
    '@import "tailwindcss";',
    '@import "@nuxt/ui";',
    '',
    themeCss(theme)
  ].join('\n')
})

const isPalette = (value: string) => (PALETTE_NAMES as readonly string[]).includes(value)

const appConfigFile = (model: Model, theme: Theme): GeneratedFile => {
  const { name, description } = model.project
  return {
    path: corePaths.appConfig,
    owner: 'managed',
    source: '.bildr/bildr.json',
    content: file([
      header('.bildr/bildr.json and .bildr/theme.json'),
      'export default defineAppConfig({',
      '  site: {',
      `    name: ${tsString(name)},`,
      `    description: ${tsString(description ?? `${name}, built with bildr.`)}`,
      '  },',
      '  ui: {',
      '    colors: {',
      // Nuxt UI takes palette names only; hex and env colours live in theme.css, which wins.
      THEME_COLORS.map(color => `      ${color}: ${tsString(isPalette(theme.colors[color]) ? theme.colors[color] : DEFAULT_THEME.colors[color])}`).join(',\n'),
      '    }',
      '  }',
      '})'
    ])
  }
}

const nuxtConfigFile = (model: Model): GeneratedFile => {
  const sqlite = model.datasources.filter(source => source.kind === 'sqlite')
  // The app database is optional (V7): none for an API-only project, at most one.
  if (sqlite.length > 1) throw new Error(`The project can have at most one sqlite data source (the app database), found ${sqlite.length}`)
  // REST sources under `datasources`, API sources that run on the server under `apis`, the ones that run in the browser under `public.apis`
  // (the page reads only runtimeConfig.public, and never a secret). Apart, so a source with no auth or another secret can't change the type
  // a module's composition root reads the REST ones through (each source's client, R1').
  const rest = model.datasources.filter(source => source.kind === 'rest')
  const apis = serverApiSources(model)
  const browserApis = browserApiSources(model)
  return {
    path: corePaths.nuxtConfig,
    owner: 'managed',
    content: file([
      header('.bildr/bildr.json and .bildr/datasources'),
      'import { fileURLToPath } from \'node:url\'',
      '',
      'const here = (path: string) => fileURLToPath(new URL(path, import.meta.url))',
      '',
      'export default defineNuxtConfig({',
      '  $meta: { name: \'core\' },',
      '  modules: [\'@nuxt/ui\'],',
      '  alias: {',
      '    \'#core\': here(\'./shared\')',
      '  },',
      '  css: [here(\'./app/assets/css/theme.css\')],',
      '  nitro: { experimental: { tasks: true } },',
      '  runtimeConfig: {',
      ...(sqlite[0]
        ? [
            '    db: {',
            `      url: ${tsString(sqlite[0].defaults?.url ?? '')},`,
            '      migrationsDir: \'server/database/migrations\'',
            '    },'
          ]
        : []),
      '    // Data sources. Values come from NUXT_DATASOURCES_* env vars; see .env.example.',
      [
        rest.length ? ['    datasources: {', rest.map(sourceLine).join(',\n'), '    }'].join('\n') : '    datasources: {}',
        ...(apis.length
          ? [['    // API data sources. Values come from NUXT_APIS_* env vars; see .env.example.', '    apis: {', apis.map(sourceLine).join(',\n'), '    }'].join('\n')]
          : []),
        ...(browserApis.length
          ? [['    // API data sources that run in the browser: only their base URL, from NUXT_PUBLIC_APIS_* env vars (never a secret); see .env.example.', '    public: {', '      apis: {', browserApis.map(source => `  ${sourceLine(source)}`).join(',\n'), '      }', '    }'].join('\n')]
          : [])
      ].join(',\n'),
      '  }',
      '})'
    ])
  }
}

/** `name: { setting: default }` with every setting the env maps; secrets and unset ones start empty. An API source's base URL is in the model. */
const sourceLine = (source: DataSourceFile) =>
  `      ${camel(source.name)}: { ${Object.keys(source.env).map(key => `${key}: ${tsString((key === 'baseUrl' && source.kind === 'api' ? source.baseUrl : source.defaults?.[key]) ?? '')}`).join(', ')} }`

import { file, header, kebab, tsString } from './text.ts'

/**
 * The browser runtime of the `api` data sources (SD-5, P3): the same domain, data and tests as a server source, but no
 * composition root and no Nitro route. In `layers/apis/app/`: the client over `fetch` every browser source shares, per source its
 * composition (the HTTP repository over that client, wired to the use-cases) and the composables, which call the use-case in the
 * page. A browser source has no auth at all: P1's model refuses a secret for it, so the page never holds one and sends no credentials.
 */
export const generateBrowserRuntime = (model: Model, sources: ApiSource[]): Emitted[] => [
  browserClientFile(),
  browserClientTestFile(),
  ...sources.flatMap((source) => {
    const names = namesOf(model, source)
    return [
      compositionFile(source, names),
      ...operationsOf(source).map(operation => composableFile(source, names, operation, 'browser'))
    ]
  })
]

/**
 * The HTTP client every browser API source shares. It keeps the guards of the server client and of the editor's remote fetches
 * (node/remote.ts): calls stay on the path the model built under the base URL (a path that leaves it, or has a "." or ".." segment the
 * URL would resolve, is refused), a redirect is not followed, a timeout and a size cap. It sends no credentials and no header but
 * `accept` and, with a body, `content-type`. The base URL is read when the call is made: a missing one fails the call, not the page.
 */
const browserClientFile = (): Emitted => ({
  path: 'layers/apis/app/data/browser-client.ts',
  content: file([
    '// Generated by bildr. Editing this file detaches it from the editor.',
    'import type { Result } from \'#core/kernel/result\'',
    '',
    '/** One call to an API data source from the page. A `body` is sent as JSON; a `query` value left undefined is not sent. */',
    'export interface BrowserRequest {',
    '  method: \'GET\' | \'POST\' | \'PUT\' | \'PATCH\' | \'DELETE\'',
    '  query?: Record<string, string | number | boolean | undefined>',
    '  body?: unknown',
    '}',
    '',
    '/** A call that failed. `status` is what the API answered, or 0 when it didn\'t; `message` finishes "The API …". */',
    'export class BrowserFailure extends Error {',
    '  readonly status: number',
    '',
    '  constructor(status: number, message: string) {',
    '    super(message)',
    '    this.name = \'BrowserFailure\'',
    '    this.status = status',
    '  }',
    '}',
    '',
    'const TIMEOUT_MS = 10_000',
    '// The cap of the editor\'s own remote fetches (node/remote.ts).',
    'const MAX_BYTES = 1_000_000',
    '',
    '/** The body of the answer as text, refusing one over MAX_BYTES (by its header, or as it arrives). */',
    'const readCapped = async (response: Response): Promise<string> => {',
    '  const tooBig = () => new BrowserFailure(response.status, `answered more than ${MAX_BYTES / 1_000_000} MB`)',
    '  if (Number(response.headers.get(\'content-length\')) > MAX_BYTES) {',
    '    await response.body?.cancel()',
    '    throw tooBig()',
    '  }',
    '  const reader = response.body?.getReader()',
    '  if (!reader) return \'\'',
    '  const chunks: Uint8Array[] = []',
    '  let size = 0',
    '  for (;;) {',
    '    const { done, value } = await reader.read()',
    '    if (done) break',
    '    size += value.byteLength',
    '    if (size > MAX_BYTES) {',
    '      await reader.cancel()',
    '      throw tooBig()',
    '    }',
    '    chunks.push(value)',
    '  }',
    '  const bytes = new Uint8Array(size)',
    '  let offset = 0',
    '  for (const chunk of chunks) {',
    '    bytes.set(chunk, offset)',
    '    offset += chunk.byteLength',
    '  }',
    '  return new TextDecoder().decode(bytes)',
    '}',
    '',
    '/** The base URL as a URL ending in "/", or a failure of the call when it is missing or is not an http(s) URL. */',
    'const baseOf = (baseUrl: string): URL => {',
    '  try {',
    '    const base = new URL(baseUrl.endsWith(\'/\') ? baseUrl : `${baseUrl}/`)',
    '    if (base.protocol === \'http:\' || base.protocol === \'https:\') return base',
    '  } catch {',
    '    // Falls through to the failure below.',
    '  }',
    '  throw new BrowserFailure(0, \'has no valid base URL\')',
    '}',
    '',
    '/**',
    ' * A client over `fetch` for one API, run in the page: the path is under `baseUrl` (a path that leaves it, or has a "." or ".." segment the URL would resolve,',
    ' * is refused), a redirect is not followed (it could leave the base URL), no credentials are sent, and an answer is cut off after the timeout and the size cap.',
    ' * It answers the parsed JSON, or undefined for an empty answer.',
    ' */',
    'export const createBrowserClient = ({ baseUrl }: { baseUrl: string }) =>',
    '  async (path: string, { method, query, body }: BrowserRequest): Promise<unknown> => {',
    '    const base = baseOf(baseUrl)',
    '    const relative = path.replace(/^\\//, \'\')',
    '    // A path parameter ".." (or "%2e%2e") would be resolved by the URL to another path of the API.',
    '    if (relative.split(\'/\').some(segment => /^(?:\\.|%2e){1,2}$/i.test(segment))) throw new BrowserFailure(0, \'was asked for a path with a "." or ".." segment\')',
    '    const url = new URL(relative, base)',
    '    if (url.origin !== base.origin || url.pathname !== `${base.pathname}${relative}`) throw new BrowserFailure(0, \'was asked for a path outside its base URL\')',
    '    for (const [key, value] of Object.entries(query ?? {})) {',
    '      if (value !== undefined) url.searchParams.set(key, String(value))',
    '    }',
    '    const signal = AbortSignal.timeout(TIMEOUT_MS)',
    '    // A browser says nothing more about a failed call (a refusal by CORS looks like a network error).',
    '    const gone = () => new BrowserFailure(0, signal.aborted ? `didn\'t answer within ${TIMEOUT_MS / 1000} s` : \'couldn\\\'t be reached, or doesn\\\'t allow calls from this page\')',
    '    let response: Response',
    '    try {',
    '      response = await fetch(url, {',
    '        method,',
    '        headers: body === undefined ? { accept: \'application/json\' } : { accept: \'application/json\', \'content-type\': \'application/json\' },',
    '        ...(body === undefined ? {} : { body: JSON.stringify(body) }),',
    '        // A redirect is never followed: the browser answers an "opaqueredirect" (status 0), a server-side fetch the 3xx itself.',
    '        redirect: \'manual\',',
    '        credentials: \'omit\',',
    '        signal',
    '      })',
    '    } catch {',
    '      throw gone()',
    '    }',
    '    if (response.type === \'opaqueredirect\' || (response.status >= 300 && response.status < 400)) {',
    '      await response.body?.cancel()',
    '      throw new BrowserFailure(response.status, response.status ? `answered ${response.status}: a redirect is not followed` : \'answered a redirect, which is not followed\')',
    '    }',
    '    if (!response.ok) {',
    '      await response.body?.cancel()',
    '      throw new BrowserFailure(response.status, `answered ${response.status}`)',
    '    }',
    '    let text: string',
    '    try {',
    '      text = await readCapped(response)',
    '    } catch (cause) {',
    '      throw cause instanceof BrowserFailure ? cause : gone()',
    '    }',
    '    if (!text) return undefined',
    '    try {',
    '      return JSON.parse(text) as unknown',
    '    } catch {',
    '      throw new BrowserFailure(response.status, \'answered without JSON\')',
    '    }',
    '  }',
    '',
    '/** What a use-case answered: its value, or its error thrown with the message the UI shows (an invalid answer\'s is generic: its detail went to the console). */',
    'export const valueOrThrow = <T>(result: Result<T, { message: string }>): T => {',
    '  if (!result.ok) throw new Error(result.error.message)',
    '  return result.value',
    '}'
  ])
})

/**
 * The unit test of the client every browser source shares: `fetch` is replaced for each test and put back, no network. A call goes
 * to the path under the base URL with no credentials and no redirect followed; a dot segment, a path off the base URL, or a redirect
 * never reaches another path; a base URL that is missing fails the call, not the page.
 */
const browserClientTestFile = (): Emitted => ({
  path: 'layers/apis/test/browser-client.test.ts',
  content: file([
    '// Generated by bildr. Editing this file detaches it from the editor.',
    'import { describe, expect, it } from \'vitest\'',
    'import { BrowserFailure, createBrowserClient, valueOrThrow } from \'../app/data/browser-client\'',
    '',
    '/** Runs `body` with `fetch` answering `answer` and recording what it was asked; puts the real `fetch` back after. */',
    'const withFetch = async (answer: () => Response, body: (calls: Array<{ url: string, init: RequestInit }>) => Promise<void>) => {',
    '  const calls: Array<{ url: string, init: RequestInit }> = []',
    '  const { fetch } = globalThis',
    '  globalThis.fetch = (async (url: unknown, init: RequestInit) => {',
    '    calls.push({ url: String(url), init })',
    '    return answer()',
    '  }) as typeof fetch',
    '  try {',
    '    await body(calls)',
    '  } finally {',
    '    globalThis.fetch = fetch',
    '  }',
    '}',
    '',
    'const json = () => new Response(\'{"ok":true}\', { status: 200 })',
    '',
    'describe(\'createBrowserClient\', () => {',
    '  it(\'calls the path under the base URL, sending no credentials and following no redirect\', async () => {',
    '    await withFetch(json, async (calls) => {',
    '      const call = createBrowserClient({ baseUrl: \'https://api.example.com/v1\' })',
    '      await expect(call(\'/things\', { method: \'GET\', query: { q: \'a b\', skip: undefined } })).resolves.toEqual({ ok: true })',
    '      expect(calls.map(entry => entry.url)).toEqual([\'https://api.example.com/v1/things?q=a+b\'])',
    '      expect(calls[0]!.init).toMatchObject({ method: \'GET\', redirect: \'manual\', credentials: \'omit\', headers: { accept: \'application/json\' } })',
    '    })',
    '  })',
    '',
    '  it(\'sends a body as JSON\', async () => {',
    '    await withFetch(json, async (calls) => {',
    '      const call = createBrowserClient({ baseUrl: \'https://api.example.com/v1/\' })',
    '      await call(\'/things\', { method: \'POST\', body: { name: \'a\' } })',
    '      expect(calls[0]!.url).toBe(\'https://api.example.com/v1/things\')',
    '      expect(calls[0]!.init).toMatchObject({ method: \'POST\', body: \'{"name":"a"}\', headers: { accept: \'application/json\', \'content-type\': \'application/json\' } })',
    '    })',
    '  })',
    '',
    '  it(\'refuses a "." or ".." segment, encoded or not, without calling the API\', async () => {',
    '    await withFetch(json, async (calls) => {',
    '      const call = createBrowserClient({ baseUrl: \'https://api.example.com/v1\' })',
    '      for (const segment of [\'..\', \'.\', \'%2e%2e\', \'%2E.\', \'.%2e\', \'%2e\']) {',
    '        await expect(call(`/things/${segment}/parts`, { method: \'GET\' })).rejects.toBeInstanceOf(BrowserFailure)',
    '      }',
    '      expect(calls).toEqual([])',
    '    })',
    '  })',
    '',
    '  it(\'refuses a path that is not under the base URL, without calling the API\', async () => {',
    '    await withFetch(json, async (calls) => {',
    '      const call = createBrowserClient({ baseUrl: \'https://api.example.com/v1\' })',
    '      await expect(call(\'//evil.example.com/things\', { method: \'GET\' })).rejects.toMatchObject({ message: \'was asked for a path outside its base URL\' })',
    '      expect(calls).toEqual([])',
    '    })',
    '  })',
    '',
    '  it(\'does not follow a redirect: it is a failure, and the Location is not asked\', async () => {',
    '    await withFetch(() => new Response(null, { status: 302, headers: { location: \'https://evil.example.com/v1/things\' } }), async (calls) => {',
    '      const call = createBrowserClient({ baseUrl: \'https://api.example.com/v1\' })',
    '      await expect(call(\'/things\', { method: \'GET\' })).rejects.toMatchObject({ name: \'BrowserFailure\', status: 302 })',
    '      expect(calls.map(entry => entry.url)).toEqual([\'https://api.example.com/v1/things\'])',
    '    })',
    '  })',
    '',
    '  it(\'fails the call, not the page, when the base URL is missing or is not an http(s) URL\', async () => {',
    '    await withFetch(json, async (calls) => {',
    '      for (const baseUrl of [\'\', \'not a url\', \'ftp://api.example.com\']) {',
    '        const call = createBrowserClient({ baseUrl })',
    '        await expect(call(\'/things\', { method: \'GET\' })).rejects.toMatchObject({ status: 0, message: \'has no valid base URL\' })',
    '      }',
    '      expect(calls).toEqual([])',
    '    })',
    '  })',
    '',
    '  it(\'valueOrThrow gives the value of an ok answer and throws the message of an error\', () => {',
    '    expect(valueOrThrow({ ok: true, value: 3 })).toBe(3)',
    '    expect(() => valueOrThrow({ ok: false, error: { message: \'The "x" API answered 503.\' } })).toThrow(\'The "x" API answered 503.\')',
    '  })',
    '})'
  ])
})

/**
 * `app/data/<s>.ts`: the composition of one browser source, the only place where its use-cases meet the HTTP repository. It reads
 * only `useRuntimeConfig().public.apis.<s>.baseUrl`: the page can't hold a secret, so there is no auth here.
 */
const compositionFile = (source: ApiSource, names: SourceNames): Emitted => {
  const operations = operationsOf(source)
  const answers = operations.some(operation => operation.result)
  return {
    path: `layers/apis/app/data/${names.dir}.ts`,
    source: names.source,
    content: file([
      header(names.source),
      `// Composition of the "${source.name}" API in the browser: the only place where its use-cases meet the HTTP repository.`,
      '// It runs in the page, so it has no auth at all (a key could not stay hidden here: an API that needs one runs on the server) and sends no credentials.',
      'import { useRuntimeConfig } from \'#app\'',
      importLine(`../../shared/data/${names.dir}/client`, [{ name: 'ApiClient', type: true }]),
      importLine(`../../shared/data/${names.dir}/repositories/${names.adapterFile}`, [names.adapter]),
      importLine(`../../shared/domain/${names.dir}/errors`, [names.failure, 'remoteFailed']),
      ...operations
        .map(operation => ({ path: `../../shared/domain/${names.dir}/use-cases/${kebab(operation.name)}`, name: operation.name }))
        .sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0)
        .map(entry => importLine(entry.path, [entry.name])),
      importLine('./browser-client', ['BrowserFailure', 'createBrowserClient']),
      '',
      `/** The HTTP client of the "${source.name}" API: it calls the base URL of runtimeConfig.public.apis.${names.camel}, and nothing else. */`,
      `const ${names.client} = (): ApiClient => {`,
      `  const call = createBrowserClient({ baseUrl: useRuntimeConfig().public.apis.${names.camel}.baseUrl })`,
      '  return async (path, request) => {',
      '    try {',
      '      return await call(path, request)',
      '    } catch (cause) {',
      `      if (cause instanceof BrowserFailure) throw new ${names.failure}(remoteFailed(cause.status, cause.message))`,
      '      throw cause',
      '    }',
      '  }',
      '}',
      '',
      `/** The use-cases of the "${source.name}" API, wired to its HTTP repository. Call it in a composable's setup: it reads the runtime config. */`,
      `export const ${names.root} = () => {`,
      ...(answers
        ? [
            '  // The detail of an answer that is not what the model says (field paths, expected types) goes to the console: the error the UI sees has none.',
            `  const repository = ${names.adapter}(${names.client}(), detail => console.warn(${tsString(`The "${source.name}" API answered something unexpected: `)} + detail))`
          ]
        : [`  const repository = ${names.adapter}(${names.client}())`]),
      '  return {',
      operations.map(operation => `    ${operation.name}: ${operation.name}({ ${names.camel}: repository })`).join(',\n'),
      '  }',
      '}'
    ])
  }
}

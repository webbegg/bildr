// Embeds the static files of the golden fixture's core layer into @bildr/codegen,
// so the starter kit ships them byte for byte (packages/codegen/test/starter checks it).
// Run after changing any of these fixture files: node scripts/embed-starter-core.ts
import { readFileSync, writeFileSync } from 'node:fs'

const fixture = new URL('../fixtures/codegen/blog/', import.meta.url)
const target = new URL('../packages/codegen/src/starter/core-files.ts', import.meta.url)

/** Core files that don't depend on the model. Model-derived ones (nuxt.config, app.config, theme, layouts) are templates in starter.ts. */
const STATIC_CORE = [
  'layers/core/shared/kernel/result.ts',
  'layers/core/shared/kernel/page.ts',
  'layers/core/shared/kernel/ids.ts',
  'layers/core/shared/http/api-client.ts',
  'layers/core/shared/http/client.ts',
  'layers/core/test/infrastructure/http-client.test.ts',
  'layers/core/server/utils/db.ts',
  'layers/core/server/utils/http-error.ts',
  'layers/core/server/utils/remote.ts',
  'layers/core/server/plugins/migrate.ts',
  'layers/core/app/data/query-client.ts',
  'layers/core/app/data/results.ts',
  'layers/core/app/composables/useVariantState.ts',
  'layers/core/app/types/page-meta.d.ts',
  'layers/core/app/app.vue',
  'layers/core/app/error.vue'
]

/** Root files that are the same for every project. */
const STATIC_ROOT = [
  'nuxt.config.ts',
  'tsconfig.json',
  '.gitignore',
  'pnpm-workspace.yaml',
  'app/README.md',
  'server/README.md',
  'eslint.config.mjs',
  'drizzle.config.ts'
]

const entries = (paths: string[]) => paths.map(path => `  ${JSON.stringify(path)}: ${JSON.stringify(readFileSync(new URL(path, fixture), 'utf8'))}`).join(',\n')

writeFileSync(target, `/* eslint-disable */
// Generated by scripts/embed-starter-core.ts from fixtures/codegen/blog. Do not edit: change the fixture and re-run the script.

/** Static files of the core layer (owner: managed). */
export const STARTER_CORE_FILES: Record<string, string> = {
${entries(STATIC_CORE)}
}

/** Static root files: managed tooling configs and scaffold-once project files. */
export const STARTER_ROOT_FILES: Record<string, string> = {
${entries(STATIC_ROOT)}
}
`)
console.log(`Embedded ${STATIC_CORE.length + STATIC_ROOT.length} files into ${target.pathname}`)
